CREATE TABLE KBOT_PLATFORM_USER_ROLE (
    USER_ID VARCHAR2(256 CHAR) NOT NULL,
    ROLE_CODE VARCHAR2(64 CHAR) NOT NULL,
    APP_ID VARCHAR2(64 CHAR) DEFAULT 'platform' NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PLATFORM_USER_ROLE PRIMARY KEY (USER_ID, ROLE_CODE),
    CONSTRAINT FK_PLATFORM_USER_ROLE_USER FOREIGN KEY (USER_ID)
        REFERENCES KBOT_PLATFORM_USER (USER_ID),
    CONSTRAINT FK_PLATFORM_USER_ROLE_ROLE FOREIGN KEY (APP_ID, ROLE_CODE)
        REFERENCES KBOT_APP_ROLE (APP_ID, ROLE_CODE),
    CONSTRAINT CK_PLATFORM_USER_ROLE_APP CHECK (APP_ID = 'platform'),
    CONSTRAINT CK_PLATFORM_USER_ROLE_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE KBOT_APP_DOMAIN (
    APP_ID VARCHAR2(64 CHAR) NOT NULL,
    DOMAIN_ID NUMBER(38) NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_DOMAIN PRIMARY KEY (APP_ID, DOMAIN_ID),
    CONSTRAINT FK_APP_DOMAIN_APP FOREIGN KEY (APP_ID) REFERENCES KBOT_PLATFORM_APP (APP_ID),
    CONSTRAINT FK_APP_DOMAIN_DOMAIN FOREIGN KEY (DOMAIN_ID) REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_APP_DOMAIN_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE KBOT_APP_MEMBER (
    APP_ID VARCHAR2(64 CHAR) NOT NULL,
    USER_ID VARCHAR2(256 CHAR) NOT NULL,
    MEMBER_SOURCE VARCHAR2(32 CHAR) NOT NULL,
    IS_INITIAL_ADMIN CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    GRANTED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_MEMBER PRIMARY KEY (APP_ID, USER_ID),
    CONSTRAINT FK_APP_MEMBER_APP FOREIGN KEY (APP_ID) REFERENCES KBOT_PLATFORM_APP (APP_ID),
    CONSTRAINT FK_APP_MEMBER_USER FOREIGN KEY (USER_ID) REFERENCES KBOT_PLATFORM_USER (USER_ID),
    CONSTRAINT CK_APP_MEMBER_SOURCE CHECK (MEMBER_SOURCE IN ('APP_CREATED', 'PLATFORM_GRANT', 'APP_INITIAL_ADMIN')),
    CONSTRAINT CK_APP_MEMBER_INITIAL CHECK (IS_INITIAL_ADMIN IN ('Y', 'N')),
    CONSTRAINT CK_APP_MEMBER_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_APP_INITIAL_ACTIVE CHECK (IS_INITIAL_ADMIN = 'N' OR STATUS = 'ACTIVE')
);

CREATE UNIQUE INDEX UK_APP_INITIAL_ADMIN ON KBOT_APP_MEMBER (
    CASE WHEN IS_INITIAL_ADMIN = 'Y' THEN APP_ID END
);
CREATE INDEX IX_APP_MEMBER_USER ON KBOT_APP_MEMBER (USER_ID, STATUS, APP_ID);

CREATE TABLE KBOT_APP_MEMBER_ROLE (
    APP_ID VARCHAR2(64 CHAR) NOT NULL,
    USER_ID VARCHAR2(256 CHAR) NOT NULL,
    ROLE_CODE VARCHAR2(64 CHAR) NOT NULL,
    SCOPE_MODE VARCHAR2(32 CHAR) DEFAULT 'SELECTED_DOMAINS' NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_MEMBER_ROLE PRIMARY KEY (APP_ID, USER_ID, ROLE_CODE),
    CONSTRAINT FK_APP_MEMBER_ROLE_ROLE FOREIGN KEY (APP_ID, ROLE_CODE)
        REFERENCES KBOT_APP_ROLE (APP_ID, ROLE_CODE),
    CONSTRAINT FK_APP_MEMBER_ROLE_MEMBER FOREIGN KEY (APP_ID, USER_ID)
        REFERENCES KBOT_APP_MEMBER (APP_ID, USER_ID),
    CONSTRAINT CK_APP_MEMBER_ROLE_SCOPE CHECK (SCOPE_MODE IN ('ALL_APP_DOMAINS', 'SELECTED_DOMAINS')),
    CONSTRAINT CK_APP_MEMBER_ROLE_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE KBOT_APP_MEMBER_ROLE_SCOPE (
    APP_ID VARCHAR2(64 CHAR) NOT NULL,
    USER_ID VARCHAR2(256 CHAR) NOT NULL,
    ROLE_CODE VARCHAR2(64 CHAR) NOT NULL,
    DOMAIN_ID NUMBER(38) NOT NULL,
    CONSTRAINT PK_APP_MEMBER_ROLE_SCOPE PRIMARY KEY (APP_ID, USER_ID, ROLE_CODE, DOMAIN_ID),
    CONSTRAINT FK_APP_MEMBER_SCOPE_BINDING FOREIGN KEY (APP_ID, USER_ID, ROLE_CODE)
        REFERENCES KBOT_APP_MEMBER_ROLE (APP_ID, USER_ID, ROLE_CODE),
    CONSTRAINT FK_APP_MEMBER_SCOPE_DOMAIN FOREIGN KEY (APP_ID, DOMAIN_ID)
        REFERENCES KBOT_APP_DOMAIN (APP_ID, DOMAIN_ID)
);

MERGE INTO KBOT_APP_ROLE target
USING (
    SELECT APP_ID, 'app_admin' ROLE_CODE,
           DISPLAY_NAME || ' 初始管理员' DISPLAY_NAME
      FROM KBOT_PLATFORM_APP
     WHERE APP_ID <> 'platform' AND MEMBER_ASSIGNABLE = 'Y'
) source
ON (target.APP_ID = source.APP_ID AND target.ROLE_CODE = source.ROLE_CODE)
WHEN NOT MATCHED THEN INSERT (
    APP_ID, ROLE_CODE, DISPLAY_NAME, IS_SYSTEM,
    SCOPE_POLICY, STATUS, ROW_VERSION
) VALUES (
    source.APP_ID, source.ROLE_CODE, source.DISPLAY_NAME,
    'Y', 'ALL_APP_DOMAINS', 'ACTIVE', 1
);

INSERT INTO KBOT_APP_DOMAIN (APP_ID, DOMAIN_ID, STATUS, CREATED_BY, CREATED_AT)
SELECT APP_ID, DOMAIN_ID,
       CASE WHEN MAX(CASE WHEN STATUS = 'ACTIVE' THEN 1 ELSE 0 END) = 1 THEN 'ACTIVE' ELSE 'DISABLED' END,
       'migration:access_scope', SYSTIMESTAMP
  FROM KBOT_APP_MEMBER_ROLE_OLD
 WHERE APP_ID <> 'platform'
 GROUP BY APP_ID, DOMAIN_ID;

INSERT INTO KBOT_APP_MEMBER (
    APP_ID, USER_ID, MEMBER_SOURCE, IS_INITIAL_ADMIN,
    STATUS, GRANTED_BY, CREATED_AT, UPDATED_AT
)
SELECT old_role.APP_ID, old_role.USER_ID,
       CASE WHEN user_row.ACCOUNT_ORIGIN = 'PLATFORM' THEN 'PLATFORM_GRANT' ELSE 'APP_CREATED' END,
       'N',
       CASE WHEN MAX(CASE WHEN old_role.STATUS = 'ACTIVE' THEN 1 ELSE 0 END) = 1 THEN 'ACTIVE' ELSE 'DISABLED' END,
       'migration:access_scope', MIN(old_role.CREATED_AT), SYSTIMESTAMP
  FROM KBOT_APP_MEMBER_ROLE_OLD old_role
  JOIN KBOT_PLATFORM_USER user_row ON user_row.USER_ID = old_role.USER_ID
 WHERE old_role.APP_ID <> 'platform'
   AND old_role.USER_ID <> 'ADMIN'
 GROUP BY old_role.APP_ID, old_role.USER_ID, user_row.ACCOUNT_ORIGIN;

INSERT INTO KBOT_APP_MEMBER_ROLE (
    APP_ID, USER_ID, ROLE_CODE, SCOPE_MODE, STATUS, CREATED_BY, CREATED_AT
)
SELECT APP_ID, USER_ID,
       CASE WHEN ROLE_CODE = 'system_admin' THEN 'app_admin' ELSE ROLE_CODE END,
       'SELECTED_DOMAINS',
       CASE WHEN MAX(CASE WHEN STATUS = 'ACTIVE' THEN 1 ELSE 0 END) = 1 THEN 'ACTIVE' ELSE 'DISABLED' END,
       'migration:access_scope', MIN(CREATED_AT)
  FROM KBOT_APP_MEMBER_ROLE_OLD
 WHERE APP_ID <> 'platform'
   AND USER_ID <> 'ADMIN'
 GROUP BY APP_ID, USER_ID,
          CASE WHEN ROLE_CODE = 'system_admin' THEN 'app_admin' ELSE ROLE_CODE END;

INSERT INTO KBOT_APP_MEMBER_ROLE_SCOPE (APP_ID, USER_ID, ROLE_CODE, DOMAIN_ID)
SELECT DISTINCT APP_ID, USER_ID,
       CASE WHEN ROLE_CODE = 'system_admin' THEN 'app_admin' ELSE ROLE_CODE END,
       DOMAIN_ID
  FROM KBOT_APP_MEMBER_ROLE_OLD
 WHERE APP_ID <> 'platform'
   AND USER_ID <> 'ADMIN';

MERGE INTO KBOT_PERMISSION target
USING (
    SELECT 'platform:domain_manage' PERMISSION_CODE, 'platform' APP_ID, '管理平台 Domain' DISPLAY_NAME FROM DUAL
    UNION ALL SELECT 'platform:app_manage', 'platform', '管理 App 生命周期和初始管理员' FROM DUAL
    UNION ALL SELECT 'platform:app_grant_manage', 'platform', '显式授予平台用户 App 权限' FROM DUAL
    UNION ALL SELECT 'knowledge_retrieval:role_manage', 'knowledge_retrieval', '管理应用角色' FROM DUAL
    UNION ALL SELECT 'aiops:role_manage', 'aiops', '管理 AIOps 角色' FROM DUAL
    UNION ALL SELECT 'km_asset:role_manage', 'km_asset', '管理 KM Asset 角色' FROM DUAL
) source
ON (target.PERMISSION_CODE = source.PERMISSION_CODE)
WHEN NOT MATCHED THEN INSERT (PERMISSION_CODE, APP_ID, DISPLAY_NAME)
VALUES (source.PERMISSION_CODE, source.APP_ID, source.DISPLAY_NAME);

MERGE INTO KBOT_APP_ROLE target
USING (
    SELECT 'platform' APP_ID, 'platform_admin' ROLE_CODE,
           '平台管理员' DISPLAY_NAME FROM DUAL
) source
ON (target.APP_ID = source.APP_ID AND target.ROLE_CODE = source.ROLE_CODE)
WHEN MATCHED THEN UPDATE SET
    target.IS_SYSTEM = 'Y', target.SCOPE_POLICY = 'PLATFORM', target.STATUS = 'ACTIVE'
WHEN NOT MATCHED THEN INSERT (
    APP_ID, ROLE_CODE, DISPLAY_NAME, IS_SYSTEM,
    SCOPE_POLICY, STATUS, ROW_VERSION
) VALUES (
    source.APP_ID, source.ROLE_CODE, source.DISPLAY_NAME,
    'Y', 'PLATFORM', 'ACTIVE', 1
);

UPDATE KBOT_APP_ROLE
   SET IS_SYSTEM = 'Y',
       SCOPE_POLICY = CASE WHEN APP_ID = 'platform' THEN 'PLATFORM' ELSE SCOPE_POLICY END
 WHERE ROLE_CODE IN ('platform_admin', 'user', 'contributor', 'reviewer', 'operator', 'approver');

MERGE INTO KBOT_APP_ROLE target
USING (
    SELECT APP_ID, 'app_admin' ROLE_CODE,
           DISPLAY_NAME || ' 初始管理员' DISPLAY_NAME
      FROM KBOT_PLATFORM_APP
     WHERE APP_ID <> 'platform' AND MEMBER_ASSIGNABLE = 'Y'
) source
ON (target.APP_ID = source.APP_ID AND target.ROLE_CODE = source.ROLE_CODE)
WHEN NOT MATCHED THEN INSERT (
    APP_ID, ROLE_CODE, DISPLAY_NAME, IS_SYSTEM,
    SCOPE_POLICY, STATUS, ROW_VERSION
) VALUES (
    source.APP_ID, source.ROLE_CODE, source.DISPLAY_NAME,
    'Y', 'ALL_APP_DOMAINS', 'ACTIVE', 1
);

MERGE INTO KBOT_APP_ROLE_PERMISSION target
USING (
    SELECT permission.APP_ID, 'app_admin' ROLE_CODE, permission.PERMISSION_CODE
      FROM KBOT_PERMISSION permission
     WHERE permission.APP_ID <> 'platform'
) source
ON (
    target.APP_ID = source.APP_ID
    AND target.ROLE_CODE = source.ROLE_CODE
    AND target.PERMISSION_CODE = source.PERMISSION_CODE
)
WHEN NOT MATCHED THEN INSERT (APP_ID, ROLE_CODE, PERMISSION_CODE)
VALUES (source.APP_ID, source.ROLE_CODE, source.PERMISSION_CODE);

MERGE INTO KBOT_APP_ROLE_PERMISSION target
USING (
    SELECT 'platform' APP_ID, 'platform_admin' ROLE_CODE, PERMISSION_CODE
      FROM KBOT_PERMISSION WHERE APP_ID = 'platform'
) source
ON (
    target.APP_ID = source.APP_ID
    AND target.ROLE_CODE = source.ROLE_CODE
    AND target.PERMISSION_CODE = source.PERMISSION_CODE
)
WHEN NOT MATCHED THEN INSERT (APP_ID, ROLE_CODE, PERMISSION_CODE)
VALUES (source.APP_ID, source.ROLE_CODE, source.PERMISSION_CODE);

INSERT INTO KBOT_PLATFORM_USER_ROLE (
    USER_ID, ROLE_CODE, STATUS, CREATED_BY, CREATED_AT
)
SELECT DISTINCT old_role.USER_ID, 'platform_admin', 'ACTIVE',
       'migration:access_scope', SYSTIMESTAMP
  FROM KBOT_APP_MEMBER_ROLE_OLD old_role
  JOIN KBOT_PLATFORM_USER user_row ON user_row.USER_ID = old_role.USER_ID
 WHERE old_role.APP_ID = 'platform'
   AND user_row.ACCOUNT_ORIGIN = 'PLATFORM';

MERGE INTO KBOT_PLATFORM_USER_ROLE target
USING (SELECT 'ADMIN' USER_ID, 'platform_admin' ROLE_CODE FROM DUAL) source
ON (target.USER_ID = source.USER_ID AND target.ROLE_CODE = source.ROLE_CODE)
WHEN MATCHED THEN UPDATE SET target.STATUS = 'ACTIVE'
WHEN NOT MATCHED THEN INSERT (
    USER_ID, ROLE_CODE, STATUS, CREATED_BY, CREATED_AT
) VALUES (
    source.USER_ID, source.ROLE_CODE, 'ACTIVE',
    'migration:access_scope', SYSTIMESTAMP
);

DROP TABLE KBOT_APP_MEMBER_ROLE_OLD PURGE;

DELETE FROM KBOT_APP_ROLE_PERMISSION WHERE ROLE_CODE = 'system_admin';
DELETE FROM KBOT_APP_ROLE WHERE ROLE_CODE = 'system_admin';

