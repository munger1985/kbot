-- 将既有 KBot 4.0 用户授权一次性切换为平台/App/Domain 分层模型。
-- SQL Developer 使用 Run Script（F5）执行；执行前必须完成数据库备份。
-- 本脚本不创建初始 App 管理员，迁移后由平台 ADMIN 调用专用接口创建。
-- 旧业务 system_admin 会转换为普通 App Grant/App 用户的 app_admin 角色，
-- 不会被标记为受保护的唯一初始管理员。

SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    l_old_column_count PLS_INTEGER;
    l_new_table_count  PLS_INTEGER;
    l_admin_count      PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO l_old_column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'KBOT_APP_MEMBER_ROLE'
       AND COLUMN_NAME = 'DOMAIN_ID';

    SELECT COUNT(*) INTO l_new_table_count
      FROM USER_TABLES
     WHERE TABLE_NAME IN (
        'KBOT_PLATFORM_APP', 'KBOT_APP_MEMBER',
        'KBOT_APP_MEMBER_ROLE_SCOPE'
     );

    SELECT COUNT(*) INTO l_admin_count
      FROM KBOT_PLATFORM_USER user_row
      JOIN KBOT_PLATFORM_USER_CREDENTIAL credential
        ON credential.USER_ID = user_row.USER_ID
     WHERE user_row.USER_ID = 'ADMIN';

    IF l_old_column_count <> 1 OR l_new_table_count <> 0 THEN
        raise_application_error(
            -20001,
            '当前 Schema 不是可迁移的旧权限模型，或迁移已经执行。'
        );
    END IF;
    IF l_admin_count <> 1 THEN
        raise_application_error(
            -20002,
            '未找到大写 ADMIN 及其凭据，请先完成管理员账号规范化。'
        );
    END IF;
END;
/

CREATE TABLE KBOT_PLATFORM_APP (
    APP_ID VARCHAR2(64 CHAR) PRIMARY KEY,
    DISPLAY_NAME VARCHAR2(256 CHAR) NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    MEMBER_ASSIGNABLE CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_PLATFORM_APP_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_PLATFORM_APP_MEMBER CHECK (MEMBER_ASSIGNABLE IN ('Y', 'N'))
);

INSERT INTO KBOT_PLATFORM_APP (APP_ID, DISPLAY_NAME, STATUS, MEMBER_ASSIGNABLE)
SELECT APP_ID,
       CASE APP_ID
           WHEN 'platform' THEN '平台管理'
           WHEN 'knowledge_retrieval' THEN '知识检索'
           WHEN 'aiops' THEN 'AIOps'
           WHEN 'km_asset' THEN 'KM Asset'
           ELSE APP_ID
       END,
       'ACTIVE',
       CASE WHEN APP_ID = 'platform' THEN 'N' ELSE 'Y' END
  FROM (
      SELECT DISTINCT APP_ID FROM KBOT_PERMISSION
      UNION SELECT 'platform' FROM DUAL
      UNION SELECT 'knowledge_retrieval' FROM DUAL
      UNION SELECT 'aiops' FROM DUAL
      UNION SELECT 'km_asset' FROM DUAL
  );

ALTER TABLE KBOT_PLATFORM_USER ADD (
    ACCOUNT_ORIGIN VARCHAR2(16 CHAR) DEFAULT 'PLATFORM' NOT NULL,
    OWNER_APP_ID VARCHAR2(64 CHAR),
    IS_PROTECTED CHAR(1 CHAR) DEFAULT 'N' NOT NULL
);

UPDATE KBOT_PLATFORM_USER user_row
   SET ACCOUNT_ORIGIN = 'APP',
       OWNER_APP_ID = (
           SELECT MIN(member_role.APP_ID)
             FROM KBOT_APP_MEMBER_ROLE member_role
            WHERE member_role.USER_ID = user_row.USER_ID
              AND member_role.APP_ID <> 'platform'
       )
 WHERE user_row.USER_ID <> 'ADMIN'
   AND NOT EXISTS (
       SELECT 1 FROM KBOT_APP_MEMBER_ROLE platform_role
        WHERE platform_role.USER_ID = user_row.USER_ID
          AND platform_role.APP_ID = 'platform'
   )
   AND 1 = (
       SELECT COUNT(DISTINCT member_role.APP_ID)
         FROM KBOT_APP_MEMBER_ROLE member_role
        WHERE member_role.USER_ID = user_row.USER_ID
          AND member_role.APP_ID <> 'platform'
   );

UPDATE KBOT_PLATFORM_USER
   SET ACCOUNT_ORIGIN = 'PLATFORM',
       OWNER_APP_ID = NULL,
       IS_PROTECTED = CASE WHEN USER_ID = 'ADMIN' THEN 'Y' ELSE 'N' END,
       MAX_SECURITY_LEVEL = CASE WHEN USER_ID = 'ADMIN' THEN 3 ELSE MAX_SECURITY_LEVEL END,
       STATUS = CASE WHEN USER_ID = 'ADMIN' THEN 'ACTIVE' ELSE STATUS END,
       UPDATED_AT = SYSTIMESTAMP
 WHERE ACCOUNT_ORIGIN = 'PLATFORM' OR USER_ID = 'ADMIN';

