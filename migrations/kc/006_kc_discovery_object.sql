-- Bundle/Document discovery projections.  Profile text is not a citation.
CREATE TABLE KBOT_KC_DISCOVERY_OBJECT (
    DISCOVERY_OBJECT_ID NUMBER(38) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COLLECTION_ID NUMBER(38) NOT NULL, BUNDLE_ID NUMBER(38) NOT NULL,
    BUNDLE_REVISION_ID NUMBER(38) NOT NULL, BUNDLE_REVISION_DOCUMENT_ID NUMBER(38),
    DOCUMENT_ID NUMBER(38), DOCUMENT_VERSION_ID NUMBER(38),
    OBJECT_TYPE VARCHAR2(16 CHAR) NOT NULL, PROFILE_KEY VARCHAR2(256 CHAR) NOT NULL,
    DISPLAY_TITLE VARCHAR2(512 CHAR) NOT NULL, PROFILE_TEXT CLOB NOT NULL,
    FACET_JSON CLOB, COVERAGE_JSON CLOB NOT NULL, PROFILE_HASH VARCHAR2(64 CHAR) NOT NULL,
    PROFILE_SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    EMBEDDING VECTOR, EMBEDDING_MODEL_ID NUMBER(38), EMBEDDING_MODEL_KEY VARCHAR2(256 CHAR),
    EMBEDDING_CONFIG_FINGERPRINT VARCHAR2(64 CHAR), EMBEDDING_INPUT_HASH VARCHAR2(64 CHAR),
    INDEXED_AT TIMESTAMP(6) WITH TIME ZONE,
    SECURITY_LEVEL NUMBER(3) NOT NULL, QUALITY_SCORE NUMBER(8,6),
    DISCOVERY_STATUS VARCHAR2(16 CHAR) NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR), UPDATED_BY VARCHAR2(256 CHAR),
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_KC_DISCOVERY_REV_KEY UNIQUE (BUNDLE_REVISION_ID, PROFILE_KEY),
    CONSTRAINT CK_KC_DISCOVERY_TYPE CHECK (OBJECT_TYPE IN ('BUNDLE', 'DOCUMENT')),
    CONSTRAINT CK_KC_DISCOVERY_STATUS CHECK (DISCOVERY_STATUS IN ('STAGED', 'ACTIVE', 'DELETING', 'FAILED')),
    CONSTRAINT CK_KC_DISCOVERY_FACET_JSON CHECK (FACET_JSON IS JSON),
    CONSTRAINT CK_KC_DISCOVERY_COVERAGE_JSON CHECK (COVERAGE_JSON IS JSON),
    CONSTRAINT CK_KC_DISCOVERY_BUNDLE_KEY CHECK (
        (OBJECT_TYPE = 'BUNDLE' AND BUNDLE_REVISION_DOCUMENT_ID IS NULL AND DOCUMENT_ID IS NULL)
        OR (OBJECT_TYPE = 'DOCUMENT' AND BUNDLE_REVISION_DOCUMENT_ID IS NOT NULL AND DOCUMENT_ID IS NOT NULL)
    )
);
CREATE INDEX IX_KC_DISCOVERY_SCOPE_STATUS ON KBOT_KC_DISCOVERY_OBJECT (COLLECTION_ID, DISCOVERY_STATUS, SECURITY_LEVEL);
CREATE INDEX IX_KC_DISCOVERY_REV_TYPE ON KBOT_KC_DISCOVERY_OBJECT (BUNDLE_REVISION_ID, OBJECT_TYPE, DISCOVERY_STATUS);
