    IS_ACTIVE       VARCHAR2(1) DEFAULT '1' NOT NULL,
    CREATED_BY      VARCHAR2(50),
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY      VARCHAR2(50),
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE KBOT_AGENT_WORKFLOW IS 'SOP 工作流表 - 存储用户自定义的任务执行蓝图';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.ID IS 'UUID, 主键';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.AGENT_ID IS '所属 Agent ID';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.NAME IS '流程名称';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.DESCRIPTION IS '流程语义描述';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.EMBEDDING IS 'Oracle 23ai 语义向量';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.NODES IS '节点信息（JSON）';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.EDGES IS '连接信息（JSON）';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.CONFIG IS '全局配置（JSON）';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.EXEC_MODE IS 'SOP 强制执行模式: strict/guided/suggested';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.IS_ACTIVE IS '是否启用: 1=启用, 0=禁用';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.CREATED_BY IS '创建人';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.CREATED_AT IS '创建时间';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.UPDATED_BY IS '最后修改人';
COMMENT ON COLUMN KBOT_AGENT_WORKFLOW.UPDATED_AT IS '更新时间';

