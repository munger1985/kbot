-- KBot 4.0 Data Query：审计、外键、条件唯一索引与只读视图。

CREATE TABLE KBOT_DQ_AUDIT (
    AUDIT_ID RAW(16) PRIMARY KEY,
    DATA_QUERY_RUN_ID RAW(16),
    DOMAIN_ID NUMBER(38) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR),
    TRACE_ID VARCHAR2(128 CHAR) NOT NULL,
    ACTION VARCHAR2(128 CHAR) NOT NULL,
    PAYLOAD_JSON JSON NOT NULL,
    PREVIOUS_HASH VARCHAR2(64 CHAR),
    CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_DQ_AUDIT_HASH CHECK (LENGTH(CONTENT_HASH) = 64 AND (PREVIOUS_HASH IS NULL OR LENGTH(PREVIOUS_HASH) = 64))
);

