CREATE UNIQUE INDEX UX_DQ_MODEL_ACTIVE ON KBOT_DQ_MODEL_VERSION (
    CASE WHEN STATUS = 'ACTIVE' THEN SEMANTIC_MODEL_ID END
);
CREATE UNIQUE INDEX UX_DQ_EVENT_KEY ON KBOT_DQ_EVENT (
    CASE WHEN EVENT_KEY IS NOT NULL THEN DATA_QUERY_RUN_ID END,
    CASE WHEN EVENT_KEY IS NOT NULL THEN EVENT_KEY END
);
CREATE INDEX IX_DQ_AUDIT_SCOPE ON KBOT_DQ_AUDIT (DOMAIN_ID, CREATED_AT, AUDIT_ID);

CREATE OR REPLACE VIEW KBOT_V_DQ_SOURCE AS
SELECT DATA_SOURCE_ID, DOMAIN_ID, DISPLAY_NAME, SOURCE_TYPE, STATUS,
       CURRENT_VERSION, CAPABILITIES_JSON, ERROR_CODE, ROW_VERSION, UPDATED_AT
FROM KBOT_DQ_DATA_SOURCE;

CREATE OR REPLACE VIEW KBOT_V_DQ_RUN AS
SELECT DATA_QUERY_RUN_ID, DOMAIN_ID, ACTOR_ID, CONSUMER_APP_ID, AGENT_ID,
       AGENT_VERSION_ID, TRACE_ID, STATUS,
       ERROR_CODE, ROW_VERSION, CREATED_AT, COMPLETED_AT
FROM KBOT_DQ_RUN;

CREATE OR REPLACE VIEW KBOT_V_DQ_SCHEMA_VERSION AS
SELECT 'data_query' AS COMPONENT, 1 AS SCHEMA_VERSION FROM DUAL;
