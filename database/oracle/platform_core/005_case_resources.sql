-- 系统案例资源持久化事件：一 Domain 一记录，保留 Collection 身份。
CREATE TABLE KBOT_PLATFORM_CASE_RESOURCE (
    DOMAIN_ID NUMBER(38) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR) NOT NULL,
    COLLECTION_ID RAW(16),
    CREATION_ALLOWED NUMBER(10) NOT NULL,
    STATUS VARCHAR2(24 CHAR) NOT NULL,
    CONFIGURATION_STATUS VARCHAR2(32 CHAR) NOT NULL,
    MISSING_MODEL_ROLES JSON NOT NULL,
    ERROR_CODE VARCHAR2(128 CHAR),
    ATTEMPT_COUNT NUMBER(10) NOT NULL,
    NEXT_ATTEMPT_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    LEASE_TOKEN VARCHAR2(36 CHAR),
    LEASE_UNTIL TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_PLATFORM_CASE_RESOURCE PRIMARY KEY (DOMAIN_ID)
);

CREATE INDEX IX_PLATFORM_CASE_RESOURCE_DUE
    ON KBOT_PLATFORM_CASE_RESOURCE (NEXT_ATTEMPT_AT);
