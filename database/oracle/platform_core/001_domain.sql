-- KBot 4.0 平台 Domain 注册表。
-- Domain 是 Main API 的认证边界，不属于 KC、Agent 或 AIOps 领域。

CREATE TABLE KBOT_PLATFORM_DOMAIN (
    DOMAIN_ID NUMBER(38) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(256 CHAR) NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR),
    UPDATED_BY VARCHAR2(256 CHAR),
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_PLATFORM_DOMAIN_APP_NAME UNIQUE (NAME),
    CONSTRAINT CK_PLATFORM_DOMAIN_STATUS
        CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_PLATFORM_DOMAIN_ROW_VERSION CHECK (ROW_VERSION > 0)
);

CREATE INDEX IX_PLATFORM_DOMAIN_APP_STATUS
    ON KBOT_PLATFORM_DOMAIN (STATUS, DOMAIN_ID);

CREATE OR REPLACE VIEW KBOT_V_PLATFORM_DOMAIN AS
SELECT
    DOMAIN_ID,
    NAME,
    STATUS,
    DESCRIPTION,
    ROW_VERSION,
    CREATED_AT,
    UPDATED_AT
FROM KBOT_PLATFORM_DOMAIN;
