-- KBot 4.0 站内通知、待办和后台任务投影。
-- 收件人是稳定 actor_id 字符串，不依赖 User、Role、Tenant 或 Permission 表。

CREATE TABLE KBOT_NOTIFICATION_OUTBOX (
    OUTBOX_ID RAW(16) PRIMARY KEY,
    PRODUCER_SERVICE VARCHAR2(64 CHAR) NOT NULL,
    EVENT_KEY VARCHAR2(256 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(160 CHAR) NOT NULL,
    EVENT_VERSION NUMBER(10) DEFAULT 1 NOT NULL,
    DOMAIN_ID NUMBER(38) NOT NULL,
    PAYLOAD_JSON JSON NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    AVAILABLE_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LEASE_TOKEN RAW(16),
    LEASE_EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE,
    LAST_ERROR_CODE VARCHAR2(128 CHAR),
    PUBLISHED_AT TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_NOTIFY_OUTBOX_EVENT UNIQUE (PRODUCER_SERVICE, EVENT_KEY),
    CONSTRAINT FK_NOTIFY_OUTBOX_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_NOTIFY_OUTBOX_STATUS CHECK
        (STATUS IN ('PENDING', 'PROCESSING', 'PUBLISHED', 'QUARANTINED')),
    CONSTRAINT CK_NOTIFY_OUTBOX_ATTEMPT CHECK (ATTEMPT_COUNT >= 0),
    CONSTRAINT CK_NOTIFY_OUTBOX_LEASE CHECK (
        (STATUS = 'PROCESSING' AND LEASE_TOKEN IS NOT NULL AND LEASE_EXPIRES_AT IS NOT NULL)
        OR (STATUS <> 'PROCESSING' AND LEASE_TOKEN IS NULL AND LEASE_EXPIRES_AT IS NULL)
    )
);

CREATE INDEX IX_NOTIFY_OUTBOX_DISPATCH
    ON KBOT_NOTIFICATION_OUTBOX (STATUS, AVAILABLE_AT, CREATED_AT);
CREATE INDEX IX_NOTIFY_OUTBOX_DOMAIN
    ON KBOT_NOTIFICATION_OUTBOX (DOMAIN_ID, CREATED_AT);

CREATE TABLE KBOT_BACKGROUND_OPERATION (
    OPERATION_ID RAW(16) PRIMARY KEY,
    DOMAIN_ID NUMBER(38) NOT NULL,
    PRODUCER_SERVICE VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_OPERATION_ID VARCHAR2(256 CHAR) NOT NULL,
    INITIATOR_ACTOR_ID VARCHAR2(256 CHAR),
    RESOURCE_TYPE VARCHAR2(80 CHAR) NOT NULL,
    RESOURCE_ID VARCHAR2(256 CHAR) NOT NULL,
    RESOURCE_NAME VARCHAR2(300 CHAR),
    STATUS VARCHAR2(24 CHAR) NOT NULL,
    PROGRESS_CURRENT NUMBER(19),
    PROGRESS_TOTAL NUMBER(19),
    ERROR_CODE VARCHAR2(128 CHAR),
    SUMMARY VARCHAR2(1000 CHAR) NOT NULL,
    LAST_OUTBOX_ID RAW(16) NOT NULL,
    LAST_OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_NOTIFY_OPERATION_SOURCE UNIQUE
        (PRODUCER_SERVICE, SOURCE_OPERATION_ID),
    CONSTRAINT FK_NOTIFY_OPER_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT FK_NOTIFY_OPER_OUTBOX FOREIGN KEY (LAST_OUTBOX_ID)
        REFERENCES KBOT_NOTIFICATION_OUTBOX (OUTBOX_ID),
    CONSTRAINT CK_NOTIFY_OPER_STATUS CHECK
        (STATUS IN ('RUNNING', 'WAITING_USER', 'SUCCEEDED', 'PARTIAL', 'FAILED')),
    CONSTRAINT CK_NOTIFY_OPER_VERSION CHECK (ROW_VERSION >= 1)
);

CREATE INDEX IX_NOTIFY_OPER_ACTOR
    ON KBOT_BACKGROUND_OPERATION (DOMAIN_ID, INITIATOR_ACTOR_ID, STATUS, UPDATED_AT);

CREATE TABLE KBOT_NOTIFICATION_INBOX (
    INBOX_ID RAW(16) PRIMARY KEY,
    EVENT_SEQUENCE NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    OUTBOX_ID RAW(16) NOT NULL,
    DOMAIN_ID NUMBER(38) NOT NULL,
    RECIPIENT_ACTOR_ID VARCHAR2(256 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(160 CHAR) NOT NULL,
    CATEGORY VARCHAR2(24 CHAR) NOT NULL,
    SEVERITY VARCHAR2(16 CHAR) NOT NULL,
    TITLE VARCHAR2(300 CHAR) NOT NULL,
    SUMMARY VARCHAR2(1000 CHAR) NOT NULL,
    RESOURCE_TYPE VARCHAR2(80 CHAR) NOT NULL,
    RESOURCE_ID VARCHAR2(256 CHAR) NOT NULL,
    OPERATION_ID RAW(16),
    READ_AT TIMESTAMP(6) WITH TIME ZONE,
    EXPIRES_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_NOTIFY_INBOX_RECIP UNIQUE (OUTBOX_ID, RECIPIENT_ACTOR_ID),
    CONSTRAINT UK_NOTIFY_INBOX_SEQ UNIQUE (EVENT_SEQUENCE),
    CONSTRAINT FK_NOTIFY_INBOX_OUTBOX FOREIGN KEY (OUTBOX_ID)
        REFERENCES KBOT_NOTIFICATION_OUTBOX (OUTBOX_ID),
    CONSTRAINT FK_NOTIFY_INBOX_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT FK_NOTIFY_INBOX_OPER FOREIGN KEY (OPERATION_ID)
        REFERENCES KBOT_BACKGROUND_OPERATION (OPERATION_ID),
    CONSTRAINT CK_NOTIFY_INBOX_CATEGORY CHECK
        (CATEGORY IN ('ACTION_REQUIRED', 'TASK', 'RESULT', 'SYSTEM')),
    CONSTRAINT CK_NOTIFY_INBOX_SEVERITY CHECK
        (SEVERITY IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT CK_NOTIFY_INBOX_VERSION CHECK (ROW_VERSION >= 1)
);

CREATE INDEX IX_NOTIFY_INBOX_ACTOR
    ON KBOT_NOTIFICATION_INBOX
        (DOMAIN_ID, RECIPIENT_ACTOR_ID, EVENT_SEQUENCE);

CREATE TABLE KBOT_NOTIFICATION_PREF (
    DOMAIN_ID NUMBER(38) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(160 CHAR) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFY_PREF PRIMARY KEY (DOMAIN_ID, ACTOR_ID, EVENT_TYPE),
    CONSTRAINT FK_NOTIFY_PREF_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_NOTIFY_PREF_ENABLED CHECK (ENABLED IN (0, 1)),
    CONSTRAINT CK_NOTIFY_PREF_VERSION CHECK (ROW_VERSION >= 1)
);

CREATE TABLE KBOT_WORK_ITEM (
    WORK_ITEM_ID RAW(16) PRIMARY KEY,
    DOMAIN_ID NUMBER(38) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR) NOT NULL,
    RESOURCE_TYPE VARCHAR2(80 CHAR) NOT NULL,
    RESOURCE_ID VARCHAR2(256 CHAR) NOT NULL,
    ACTION_TYPE VARCHAR2(160 CHAR) NOT NULL,
    TITLE VARCHAR2(300 CHAR) NOT NULL,
    SUMMARY VARCHAR2(1000 CHAR) NOT NULL,
    STATUS VARCHAR2(16 CHAR) DEFAULT 'OPEN' NOT NULL,
    OPENED_OUTBOX_ID RAW(16) NOT NULL,
    RESOLVED_OUTBOX_ID RAW(16),
    LAST_OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTIFY_WORK_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT FK_NOTIFY_WORK_OPEN FOREIGN KEY (OPENED_OUTBOX_ID)
        REFERENCES KBOT_NOTIFICATION_OUTBOX (OUTBOX_ID),
    CONSTRAINT FK_NOTIFY_WORK_RESOLVE FOREIGN KEY (RESOLVED_OUTBOX_ID)
        REFERENCES KBOT_NOTIFICATION_OUTBOX (OUTBOX_ID),
    CONSTRAINT CK_NOTIFY_WORK_STATUS CHECK
        (STATUS IN ('OPEN', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT CK_NOTIFY_WORK_VERSION CHECK (ROW_VERSION >= 1)
);

CREATE UNIQUE INDEX UX_NOTIFY_WORK_OPEN ON KBOT_WORK_ITEM (
    CASE WHEN STATUS = 'OPEN' THEN DOMAIN_ID END,
    CASE WHEN STATUS = 'OPEN' THEN ACTOR_ID END,
    CASE WHEN STATUS = 'OPEN' THEN RESOURCE_TYPE END,
    CASE WHEN STATUS = 'OPEN' THEN RESOURCE_ID END,
    CASE WHEN STATUS = 'OPEN' THEN ACTION_TYPE END
);
CREATE INDEX IX_NOTIFY_WORK_ACTOR
    ON KBOT_WORK_ITEM (DOMAIN_ID, ACTOR_ID, STATUS, UPDATED_AT);

CREATE TABLE KBOT_OPERATION_WATCH (
    OPERATION_ID RAW(16) NOT NULL,
    DOMAIN_ID NUMBER(38) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR) NOT NULL,
    NOTIFY_TERMINAL NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFY_OPERATION_WATCH PRIMARY KEY
        (OPERATION_ID, DOMAIN_ID, ACTOR_ID),
    CONSTRAINT FK_NOTIFY_WATCH_OPER FOREIGN KEY (OPERATION_ID)
        REFERENCES KBOT_BACKGROUND_OPERATION (OPERATION_ID),
    CONSTRAINT FK_NOTIFY_WATCH_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT CK_NOTIFY_WATCH_ENABLED CHECK (NOTIFY_TERMINAL IN (0, 1))
);

CREATE INDEX IX_NOTIFY_WATCH_ACTOR
    ON KBOT_OPERATION_WATCH (DOMAIN_ID, ACTOR_ID);
