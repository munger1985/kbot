DECLARE
    l_component VARCHAR2(32 CHAR);
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
    l_conflicts PLS_INTEGER;
    l_missing_group PLS_INTEGER;
BEGIN
    SELECT component, schema_version, contract_version
      INTO l_component, l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION;
    IF l_component <> 'AIOPS' OR l_schema_version <> 43
       OR l_contract_version <> 'aiops-oracle-v33' THEN
        raise_application_error(-20400,
            '本脚本仅支持 AIOPS/43/aiops-oracle-v33，当前为 '
            || l_component || '/' || l_schema_version || '/' || l_contract_version);
    END IF;
    SELECT COUNT(*) INTO l_conflicts
      FROM user_tables
     WHERE table_name IN (
        'KBOT_OPS_DATABASE_SYSTEM', 'KBOT_OPS_DATABASE_SYSTEM_MEMBER',
        'KBOT_OPS_BUSINESS_SYSTEM', 'KBOT_OPS_MANAGED_COMPONENT',
        'KBOT_OPS_MANAGED_RESOURCE', 'KBOT_OPS_BUSINESS_SYSTEM_RESOURCE',
        'KBOT_OPS_RESOURCE_RELATION', 'KBOT_OPS_RELATION_PARTICIPANT');
    IF l_conflicts <> 0 THEN
        raise_application_error(-20401, '检测到中间版或目标版对象；拒绝覆盖，请先核实 Schema。');
    END IF;
    SELECT COUNT(*) INTO l_missing_group
      FROM KBOT_OPS_TARGET
     WHERE RESPONSIBILITY_GROUP_ID IS NULL;
    IF l_missing_group <> 0 THEN
        raise_application_error(-20402,
            '有 ' || l_missing_group || ' 个 Target 未设置责任组；请先补齐。');
    END IF;
END;
