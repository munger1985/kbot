CREATE OR REPLACE VIEW KBOT_V_KM_ASSET_CURRENT AS
SELECT DOMAIN_ID, SOURCE_ID, KM_ASSET_ID, EXTERNAL_ASSET_ID AS ASSET_ID,
       SOURCE_REVISION, SOURCE_STATUS, INGESTION_STATUS, ASSET_TITLE,
       AUTHOR_MAIL, ASSET_PRODUCT, ASSET_SOLUTION, INDUSTRY_ID,
       CONTENT_CATEGORY, ASSET_STATUS, PUBLISH_DATE, LAST_UPDATE_TIME,
       KC_BUNDLE_ID, KC_BUNDLE_REVISION_ID, FAILURE_STAGE, ERROR_CODE,
       RAW_METADATA_JSON, NORMALIZED_METADATA_JSON, SYNCED_AT, COMPLETED_AT
FROM KBOT_KM_ASSET;

COMMENT ON TABLE KBOT_V_KM_ASSET_CURRENT IS 'KM Asset 当前元数据，供系统托管 Data Query 模型执行过滤、明细和聚合';
COMMENT ON COLUMN KBOT_V_KM_ASSET_CURRENT.AUTHOR_MAIL IS 'Asset 作者邮箱，可用于按用户统计 Asset 数量';
COMMENT ON COLUMN KBOT_V_KM_ASSET_CURRENT.ASSET_SOLUTION IS 'Asset 解决方案或主题';
COMMENT ON COLUMN KBOT_V_KM_ASSET_CURRENT.INGESTION_STATUS IS 'KBot 入库与解析状态';
