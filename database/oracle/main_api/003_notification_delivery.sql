-- 外部通知渠道、绑定、入口和独立投递队列。

CREATE TABLE KBOT_NOTIFY_CONNECTION (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    NAME VARCHAR2(128 CHAR) NOT NULL,
    PROVIDER VARCHAR2(24 CHAR) NOT NULL,
    APP_ID VARCHAR2(128 CHAR) NOT NULL,
    CREDENTIAL_REF VARCHAR2(512 CHAR) NOT NULL,
    CREDENTIAL_VERSION NUMBER(19) NOT NULL,
    ENABLED SMALLINT NOT NULL,
    HEALTH VARCHAR2(24 CHAR) NOT NULL,
    LAST_ERROR_CODE VARCHAR2(128 CHAR),
    CHECKED_AT TIMESTAMP WITH TIME ZONE,
    NEXT_SEND_AT TIMESTAMP WITH TIME ZONE,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE KBOT_NOTIFY_BINDING (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    CONNECTION_ID RAW(16) NOT NULL,
    ACTOR_ID VARCHAR2(256 CHAR),
    TARGET_TYPE VARCHAR2(16 CHAR) NOT NULL,
    EXTERNAL_ID VARCHAR2(256 CHAR) NOT NULL,
    STATUS VARCHAR2(24 CHAR) NOT NULL,
    VERIFIED_AT TIMESTAMP WITH TIME ZONE,
    CHALLENGE_HASH VARCHAR2(128 CHAR),
    CHALLENGE_REF VARCHAR2(512 CHAR),
    CHALLENGE_SALT VARCHAR2(64 CHAR),
    CHALLENGE_EXPIRES_AT TIMESTAMP WITH TIME ZONE,
    CHALLENGE_ATTEMPTS NUMBER(19) NOT NULL,
    CHALLENGE_SENT_AT TIMESTAMP WITH TIME ZONE,
    NEXT_SEND_AT TIMESTAMP WITH TIME ZONE,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY(CONNECTION_ID) REFERENCES KBOT_NOTIFY_CONNECTION (ID)
);

CREATE TABLE KBOT_NOTIFY_POLICY (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    CONNECTION_ID RAW(16) NOT NULL,
    EVENT_TYPES JSON NOT NULL,
    BINDING_IDS JSON NOT NULL,
    ACTOR_IDS JSON NOT NULL,
    ENABLED SMALLINT NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY(CONNECTION_ID) REFERENCES KBOT_NOTIFY_CONNECTION (ID)
);

CREATE TABLE KBOT_NOTIFY_ENTRY (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    RECIPIENT_ACTOR_ID VARCHAR2(256 CHAR),
    AUDIENCE VARCHAR2(16 CHAR) NOT NULL,
    EVENT_TYPE VARCHAR2(160 CHAR) NOT NULL,
    ROUTE_KEY VARCHAR2(160 CHAR) NOT NULL,
    ROUTE_PARAMS JSON NOT NULL,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE KBOT_NOTIFY_JOB (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    SOURCE_EVENT_ID RAW(16) NOT NULL,
    EVENT_TYPE VARCHAR2(160 CHAR) NOT NULL,
    ORIGINAL_SEVERITY VARCHAR2(16 CHAR),
    COALESCE_KEY VARCHAR2(64 CHAR),
    CONNECTION_ID RAW(16) NOT NULL,
    CONNECTION_VERSION NUMBER(19) NOT NULL,
    BINDING_ID RAW(16),
    BINDING_VERSION NUMBER(19) NOT NULL,
    RECIPIENT_ACTOR_ID VARCHAR2(256 CHAR),
    TARGET_TYPE VARCHAR2(16 CHAR) NOT NULL,
    EXTERNAL_ID VARCHAR2(256 CHAR) NOT NULL,
    PURPOSE VARCHAR2(24 CHAR) NOT NULL,
    TEMPLATE_VERSION NUMBER(19) NOT NULL,
    GENERATION NUMBER(19) NOT NULL,
    PARENT_JOB_ID RAW(16),
    ENTRY_ID RAW(16),
    CONTENT JSON NOT NULL,
    CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
    PROVIDER_UUID VARCHAR2(50 CHAR) NOT NULL,
    STATUS VARCHAR2(24 CHAR) NOT NULL,
    ATTEMPT_COUNT NUMBER(19) NOT NULL,
    RETRY_COUNT NUMBER(19) NOT NULL,
    AVAILABLE_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    LEASE_TOKEN RAW(16),
    LEASE_EXPIRES_AT TIMESTAMP WITH TIME ZONE,
    FIRST_SENT_AT TIMESTAMP WITH TIME ZONE,
    NETWORK_STARTED_AT TIMESTAMP WITH TIME ZONE,
    MESSAGE_ID VARCHAR2(256 CHAR),
    LAST_ERROR_CODE VARCHAR2(128 CHAR),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY(CONNECTION_ID) REFERENCES KBOT_NOTIFY_CONNECTION (ID),
    FOREIGN KEY(BINDING_ID) REFERENCES KBOT_NOTIFY_BINDING (ID),
    FOREIGN KEY(ENTRY_ID) REFERENCES KBOT_NOTIFY_ENTRY (ID)
);

CREATE TABLE KBOT_NOTIFY_ATTEMPT (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    JOB_ID RAW(16) NOT NULL,
    ATTEMPT_NUMBER NUMBER(19) NOT NULL,
    LEASE_TOKEN RAW(16) NOT NULL,
    STARTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    FINISHED_AT TIMESTAMP WITH TIME ZONE,
    STATUS VARCHAR2(24 CHAR) NOT NULL,
    ERROR_CODE VARCHAR2(128 CHAR),
    REQUEST_ID VARCHAR2(256 CHAR),
    MESSAGE_ID VARCHAR2(256 CHAR),
    ELAPSED_MS NUMBER(19),
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID),
    FOREIGN KEY(JOB_ID) REFERENCES KBOT_NOTIFY_JOB (ID)
);

CREATE TABLE KBOT_NOTIFY_AUDIT (
    ID RAW(16) NOT NULL,
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    ACTION VARCHAR2(80 CHAR) NOT NULL,
    OBJECT_ID RAW(16) NOT NULL,
    OUTCOME VARCHAR2(128 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE KBOT_NOTIFY_THROTTLE (
    ID VARCHAR2(32 CHAR) NOT NULL,
    NEXT_SEND_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (ID)
);

CREATE INDEX IX_NOTIFY_CONN_SCOPE ON KBOT_NOTIFY_CONNECTION (DOMAIN_ID, ENABLED);

CREATE INDEX IX_NOTIFY_BIND_SCOPE ON KBOT_NOTIFY_BINDING (CONNECTION_ID, ACTOR_ID);

CREATE INDEX IX_NOTIFY_ENTRY_EXPIRY ON KBOT_NOTIFY_ENTRY (EXPIRES_AT);

CREATE INDEX IX_NOTIFY_JOB_CLAIM ON KBOT_NOTIFY_JOB (STATUS, AVAILABLE_AT);

CREATE INDEX IX_NOTIFY_JOB_SCOPE ON KBOT_NOTIFY_JOB (DOMAIN_ID, CREATED_AT);

CREATE INDEX IX_NOTIFY_JOB_COALESCE ON KBOT_NOTIFY_JOB (COALESCE_KEY, STATUS);

CREATE INDEX IX_NOTIFY_ATTEMPT_JOB ON KBOT_NOTIFY_ATTEMPT (JOB_ID, ATTEMPT_NUMBER);

INSERT INTO KBOT_NOTIFY_THROTTLE (ID, NEXT_SEND_AT) VALUES ('external', CURRENT_TIMESTAMP);
