-- KBot 4.0 AIOps Database System 无损增量升级。
-- SQL Developer 使用 Run Script (F5) 执行；不删除现有 Target、凭据、绑定或历史。
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

DECLARE
    PROCEDURE run_ddl(p_sql CLOB) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE NOT IN (-955, -1430, -1418, -2260, -2275) THEN
                RAISE;
            END IF;
    END;
BEGIN
    run_ddl(q'[
      CREATE TABLE KBOT_OPS_DATABASE_SYSTEM (
        DATABASE_SYSTEM_ID RAW(16) PRIMARY KEY,
        DOMAIN_ID NUMBER(38) NOT NULL,
        DISPLAY_NAME VARCHAR2(256 CHAR) NOT NULL,
        DB_TYPE VARCHAR2(32 CHAR) NOT NULL,
        VERSION_CODE VARCHAR2(64 CHAR) NOT NULL,
        DEPLOYMENT_SHAPE VARCHAR2(32 CHAR) NOT NULL,
        DEPLOYMENT_CATEGORY VARCHAR2(32 CHAR) NOT NULL,
        CAPABILITIES_JSON JSON NOT NULL,
        ENVIRONMENT VARCHAR2(16 CHAR) NOT NULL,
        IMPORTANCE_LEVEL NUMBER(1) NOT NULL,
        RESPONSIBILITY_GROUP_ID RAW(16),
        DESCRIPTION CLOB,
        STATUS VARCHAR2(16 CHAR) NOT NULL,
        ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
        CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
        UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
        CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT FK_OPS_DB_SYSTEM_DOMAIN FOREIGN KEY (DOMAIN_ID)
          REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID))]');
    run_ddl('CREATE INDEX IX_OPS_DB_SYSTEM_SCOPE ON KBOT_OPS_DATABASE_SYSTEM (DOMAIN_ID, STATUS, UPDATED_AT)');

    run_ddl(q'[
      CREATE TABLE KBOT_OPS_DATABASE_SYSTEM_SITE (
        SITE_ID RAW(16) PRIMARY KEY,
        DATABASE_SYSTEM_ID RAW(16) NOT NULL,
        SITE_CODE VARCHAR2(64 CHAR) NOT NULL,
        DISPLAY_NAME VARCHAR2(256 CHAR) NOT NULL,
        EXPECTED_ROLE VARCHAR2(16 CHAR) NOT NULL,
        SORT_ORDER NUMBER(10) NOT NULL,
        CONSTRAINT FK_OPS_DB_SITE_SYSTEM FOREIGN KEY (DATABASE_SYSTEM_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM (DATABASE_SYSTEM_ID))]');
    run_ddl('CREATE INDEX IX_OPS_DB_SITE_SYSTEM ON KBOT_OPS_DATABASE_SYSTEM_SITE (DATABASE_SYSTEM_ID, SORT_ORDER)');

    run_ddl(q'[
      CREATE TABLE KBOT_OPS_DATABASE_SYSTEM_MEMBER (
        MEMBER_ID RAW(16) PRIMARY KEY,
        DATABASE_SYSTEM_ID RAW(16) NOT NULL,
        SITE_ID RAW(16) NOT NULL,
        TARGET_ID RAW(16) NOT NULL,
        MEMBER_KEY VARCHAR2(64 CHAR) NOT NULL,
        GROUP_KEY VARCHAR2(64 CHAR),
        MEMBER_TYPE VARCHAR2(32 CHAR) NOT NULL,
        EXPECTED_ROLE VARCHAR2(32 CHAR) NOT NULL,
        SORT_ORDER NUMBER(10) NOT NULL,
        CONSTRAINT FK_OPS_DB_MEMBER_SYSTEM FOREIGN KEY (DATABASE_SYSTEM_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM (DATABASE_SYSTEM_ID),
        CONSTRAINT FK_OPS_DB_MEMBER_SITE FOREIGN KEY (SITE_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM_SITE (SITE_ID),
        CONSTRAINT FK_OPS_DB_MEMBER_TARGET FOREIGN KEY (TARGET_ID)
          REFERENCES KBOT_OPS_TARGET (TARGET_ID))]');
    run_ddl('CREATE INDEX IX_OPS_DB_MEMBER_SYSTEM ON KBOT_OPS_DATABASE_SYSTEM_MEMBER (DATABASE_SYSTEM_ID, SORT_ORDER)');
    run_ddl('CREATE INDEX IX_OPS_DB_MEMBER_TARGET ON KBOT_OPS_DATABASE_SYSTEM_MEMBER (TARGET_ID)');

    run_ddl(q'[
      CREATE TABLE KBOT_OPS_DATABASE_SYSTEM_RELATION (
        RELATION_ID RAW(16) PRIMARY KEY,
        DATABASE_SYSTEM_ID RAW(16) NOT NULL,
        SOURCE_MEMBER_ID RAW(16) NOT NULL,
        TARGET_MEMBER_ID RAW(16) NOT NULL,
        RELATION_KEY VARCHAR2(64 CHAR) NOT NULL,
        RELATION_TYPE VARCHAR2(32 CHAR) NOT NULL,
        TRANSPORT_MODE VARCHAR2(16 CHAR) NOT NULL,
        SORT_ORDER NUMBER(10) NOT NULL,
        CONSTRAINT FK_OPS_DB_REL_SYSTEM FOREIGN KEY (DATABASE_SYSTEM_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM (DATABASE_SYSTEM_ID),
        CONSTRAINT FK_OPS_DB_REL_SOURCE FOREIGN KEY (SOURCE_MEMBER_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM_MEMBER (MEMBER_ID),
        CONSTRAINT FK_OPS_DB_REL_TARGET FOREIGN KEY (TARGET_MEMBER_ID)
          REFERENCES KBOT_OPS_DATABASE_SYSTEM_MEMBER (MEMBER_ID))]');
    run_ddl('CREATE INDEX IX_OPS_DB_REL_SYSTEM ON KBOT_OPS_DATABASE_SYSTEM_RELATION (DATABASE_SYSTEM_ID, SORT_ORDER)');
END;
/

MERGE INTO KBOT_OPS_DATABASE_SYSTEM d
USING (
    SELECT TARGET_ID, DOMAIN_ID, DISPLAY_NAME, DB_TYPE, VERSION_CODE,
           ENVIRONMENT, IMPORTANCE_LEVEL, RESPONSIBILITY_GROUP_ID, STATUS,
           CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT
      FROM KBOT_OPS_TARGET
) s
ON (d.DATABASE_SYSTEM_ID = s.TARGET_ID)
WHEN NOT MATCHED THEN INSERT (
    DATABASE_SYSTEM_ID, DOMAIN_ID, DISPLAY_NAME, DB_TYPE, VERSION_CODE,
    DEPLOYMENT_SHAPE, DEPLOYMENT_CATEGORY, CAPABILITIES_JSON, ENVIRONMENT,
    IMPORTANCE_LEVEL, RESPONSIBILITY_GROUP_ID, DESCRIPTION, STATUS,
    ROW_VERSION, CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT
) VALUES (
    s.TARGET_ID, s.DOMAIN_ID, s.DISPLAY_NAME, s.DB_TYPE, s.VERSION_CODE,
    'SINGLE_INSTANCE', 'SINGLE_INSTANCE', JSON_ARRAY(), s.ENVIRONMENT,
    s.IMPORTANCE_LEVEL, s.RESPONSIBILITY_GROUP_ID, NULL,
    CASE WHEN s.STATUS = 'ENABLED' THEN 'ENABLED' ELSE 'DISABLED' END,
    1, s.CREATED_BY, s.UPDATED_BY, s.CREATED_AT, s.UPDATED_AT
);

MERGE INTO KBOT_OPS_DATABASE_SYSTEM_SITE d
USING (SELECT TARGET_ID FROM KBOT_OPS_TARGET) s
ON (d.SITE_ID = s.TARGET_ID)
WHEN NOT MATCHED THEN INSERT
    (SITE_ID, DATABASE_SYSTEM_ID, SITE_CODE, DISPLAY_NAME, EXPECTED_ROLE, SORT_ORDER)
VALUES (s.TARGET_ID, s.TARGET_ID, 'MAIN', '默认站点', 'ACTIVE', 0);

MERGE INTO KBOT_OPS_DATABASE_SYSTEM_MEMBER d
USING (SELECT TARGET_ID, DB_ROLE FROM KBOT_OPS_TARGET) s
ON (d.MEMBER_ID = s.TARGET_ID)
WHEN NOT MATCHED THEN INSERT
    (MEMBER_ID, DATABASE_SYSTEM_ID, SITE_ID, TARGET_ID, MEMBER_KEY,
     GROUP_KEY, MEMBER_TYPE, EXPECTED_ROLE, SORT_ORDER)
VALUES
    (s.TARGET_ID, s.TARGET_ID, s.TARGET_ID, s.TARGET_ID, 'INSTANCE-1',
     NULL, 'INSTANCE',
     CASE WHEN s.DB_ROLE IN ('PRIMARY', 'STANDBY') THEN s.DB_ROLE ELSE 'INSTANCE' END,
     0);

DECLARE
    v_count NUMBER;
    PROCEDURE run_ddl(p_sql VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE NOT IN (-955, -1430, -1418, -2260, -2275, -2443) THEN
                RAISE;
            END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'KBOT_OPS_RECOVERY_PROFILE';
    IF v_count = 1 THEN
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD (DATABASE_SYSTEM_ID RAW(16))');
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'KBOT_OPS_RECOVERY_PROFILE' AND COLUMN_NAME = 'TARGET_ID';
        IF v_count = 1 THEN
            EXECUTE IMMEDIATE 'UPDATE KBOT_OPS_RECOVERY_PROFILE SET DATABASE_SYSTEM_ID = TARGET_ID WHERE DATABASE_SYSTEM_ID IS NULL';
            run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_PROFILE DROP CONSTRAINT FK_OPS_REC_PROFILE_TARGET');
            run_ddl('DROP INDEX IX_OPS_REC_PROFILE_TARGET');
            run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_PROFILE DROP COLUMN TARGET_ID');
        END IF;
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY (DATABASE_SYSTEM_ID NOT NULL)');
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD CONSTRAINT FK_OPS_REC_PROFILE_SYSTEM FOREIGN KEY (DATABASE_SYSTEM_ID) REFERENCES KBOT_OPS_DATABASE_SYSTEM (DATABASE_SYSTEM_ID)');
        run_ddl('CREATE INDEX IX_OPS_REC_PROFILE_SYSTEM ON KBOT_OPS_RECOVERY_PROFILE (DATABASE_SYSTEM_ID, STATUS, VERSION_NO)');
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'KBOT_OPS_RECOVERY_DRILL';
    IF v_count = 1 THEN
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL ADD (DATABASE_SYSTEM_ID RAW(16))');
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL ADD (EXECUTION_TARGET_ID RAW(16))');
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'KBOT_OPS_RECOVERY_DRILL' AND COLUMN_NAME = 'TARGET_ID';
        IF v_count = 1 THEN
            EXECUTE IMMEDIATE 'UPDATE KBOT_OPS_RECOVERY_DRILL SET DATABASE_SYSTEM_ID = TARGET_ID, EXECUTION_TARGET_ID = TARGET_ID WHERE DATABASE_SYSTEM_ID IS NULL OR EXECUTION_TARGET_ID IS NULL';
            run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL DROP CONSTRAINT FK_OPS_REC_DRILL_TARGET');
            run_ddl('DROP INDEX IX_OPS_REC_DRILL_TARGET');
            run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL DROP COLUMN TARGET_ID');
        END IF;
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL MODIFY (DATABASE_SYSTEM_ID NOT NULL, EXECUTION_TARGET_ID NOT NULL)');
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL ADD CONSTRAINT FK_OPS_REC_DRILL_SYSTEM FOREIGN KEY (DATABASE_SYSTEM_ID) REFERENCES KBOT_OPS_DATABASE_SYSTEM (DATABASE_SYSTEM_ID)');
        run_ddl('ALTER TABLE KBOT_OPS_RECOVERY_DRILL ADD CONSTRAINT FK_OPS_REC_DRILL_TARGET FOREIGN KEY (EXECUTION_TARGET_ID) REFERENCES KBOT_OPS_TARGET (TARGET_ID)');
        run_ddl('CREATE INDEX IX_OPS_REC_DRILL_SYSTEM ON KBOT_OPS_RECOVERY_DRILL (DATABASE_SYSTEM_ID, SIMULATED_FAILURE_AT, CREATED_AT)');
        run_ddl('CREATE INDEX IX_OPS_REC_DRILL_TARGET ON KBOT_OPS_RECOVERY_DRILL (EXECUTION_TARGET_ID, SIMULATED_FAILURE_AT, CREATED_AT)');
    END IF;
END;
/

COMMIT;

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    44 AS SCHEMA_VERSION,
    'aiops-oracle-v34' AS CONTRACT_VERSION
FROM DUAL;

DECLARE
    v_targets NUMBER;
    v_systems NUMBER;
    v_members NUMBER;
    v_integrity_issues NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_targets FROM KBOT_OPS_TARGET;
    SELECT COUNT(*) INTO v_systems FROM KBOT_OPS_DATABASE_SYSTEM;
    SELECT COUNT(*) INTO v_members FROM KBOT_OPS_DATABASE_SYSTEM_MEMBER;
    SELECT
        (SELECT COUNT(*) FROM KBOT_OPS_TARGET t LEFT JOIN KBOT_OPS_DATABASE_SYSTEM s ON s.DATABASE_SYSTEM_ID = t.TARGET_ID WHERE s.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_TARGET t LEFT JOIN KBOT_OPS_DATABASE_SYSTEM_MEMBER m ON m.TARGET_ID = t.TARGET_ID WHERE m.TARGET_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_SITE s LEFT JOIN KBOT_OPS_DATABASE_SYSTEM d ON d.DATABASE_SYSTEM_ID = s.DATABASE_SYSTEM_ID WHERE d.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_MEMBER m LEFT JOIN KBOT_OPS_DATABASE_SYSTEM d ON d.DATABASE_SYSTEM_ID = m.DATABASE_SYSTEM_ID WHERE d.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_MEMBER m LEFT JOIN KBOT_OPS_DATABASE_SYSTEM_SITE s ON s.SITE_ID = m.SITE_ID WHERE s.SITE_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_MEMBER m LEFT JOIN KBOT_OPS_TARGET t ON t.TARGET_ID = m.TARGET_ID WHERE t.TARGET_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_RELATION r LEFT JOIN KBOT_OPS_DATABASE_SYSTEM d ON d.DATABASE_SYSTEM_ID = r.DATABASE_SYSTEM_ID WHERE d.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_RELATION r LEFT JOIN KBOT_OPS_DATABASE_SYSTEM_MEMBER m ON m.MEMBER_ID = r.SOURCE_MEMBER_ID WHERE m.MEMBER_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_SYSTEM_RELATION r LEFT JOIN KBOT_OPS_DATABASE_SYSTEM_MEMBER m ON m.MEMBER_ID = r.TARGET_MEMBER_ID WHERE m.MEMBER_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_PROFILE p LEFT JOIN KBOT_OPS_DATABASE_SYSTEM d ON d.DATABASE_SYSTEM_ID = p.DATABASE_SYSTEM_ID WHERE d.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_DRILL r LEFT JOIN KBOT_OPS_DATABASE_SYSTEM d ON d.DATABASE_SYSTEM_ID = r.DATABASE_SYSTEM_ID WHERE d.DATABASE_SYSTEM_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_DRILL r LEFT JOIN KBOT_OPS_TARGET t ON t.TARGET_ID = r.EXECUTION_TARGET_ID WHERE t.TARGET_ID IS NULL)
      INTO v_integrity_issues
      FROM DUAL;
    IF v_systems < v_targets OR v_members < v_targets OR v_integrity_issues <> 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Database System 升级后完整性校验失败');
    END IF;
    DBMS_OUTPUT.PUT_LINE('Database System upgrade verified: targets=' || v_targets || ', systems=' || v_systems || ', members=' || v_members || ', integrity_issues=' || v_integrity_issues);
END;
