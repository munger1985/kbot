CREATE TABLE KBOT_OPS_CONVERSATION (
    CONVERSATION_ID RAW(16) PRIMARY KEY,
    DOMAIN_ID NUMBER(38) NOT NULL,
    AGENT_ID RAW(16) NOT NULL,
    AGENT_VERSION_ID RAW(16) NOT NULL,
    TARGET_ID RAW(16) NOT NULL,
    TITLE VARCHAR2(256 CHAR),
    STATUS VARCHAR2(32 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    SOURCE_TYPE VARCHAR2(24 CHAR) DEFAULT 'CHAT' NOT NULL,
    SOURCE_SITUATION_ID RAW(16),
    SOURCE_RUN_ID RAW(16),
    SOURCE_REPORT_ID RAW(16),
    LAST_TURN_NO NUMBER(19) DEFAULT 0 NOT NULL,
    LAST_MESSAGE_NO NUMBER(19) DEFAULT 0 NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_OPS_CONV_DOMAIN FOREIGN KEY (DOMAIN_ID)
        REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID),
    CONSTRAINT FK_OPS_CONV_AGENT FOREIGN KEY (AGENT_ID)
        REFERENCES KBOT_OPS_AGENT (AGENT_ID),
    CONSTRAINT FK_OPS_CONV_AGENT_VER_OWNER
        FOREIGN KEY (AGENT_VERSION_ID, AGENT_ID)
        REFERENCES KBOT_OPS_AGENT_VERSION (AGENT_VERSION_ID, AGENT_ID),
    CONSTRAINT FK_OPS_CONV_TARGET FOREIGN KEY (TARGET_ID)
        REFERENCES KBOT_OPS_TARGET (TARGET_ID),
    CONSTRAINT FK_OPS_CONV_SOURCE_SITUATION FOREIGN KEY (SOURCE_SITUATION_ID)
        REFERENCES KBOT_OPS_SITUATION (SITUATION_ID),
    CONSTRAINT FK_OPS_CONV_SOURCE_RUN FOREIGN KEY (SOURCE_RUN_ID)
        REFERENCES KBOT_OPS_RUN (OPS_RUN_ID),
    CONSTRAINT FK_OPS_CONV_SOURCE_REPORT FOREIGN KEY (SOURCE_REPORT_ID)
        REFERENCES KBOT_OPS_REPORT (REPORT_ID),
    CONSTRAINT UK_OPS_CONVERSATION_OWNER UNIQUE (CONVERSATION_ID, DOMAIN_ID),
    CONSTRAINT CK_OPS_CONV_STATUS
        CHECK (STATUS IN ('ACTIVE', 'RESOLVED', 'ARCHIVED')),
    CONSTRAINT CK_OPS_CONV_SOURCE CHECK (SOURCE_TYPE IN ('CHAT', 'SITUATION', 'RUN', 'REPORT')),
    CONSTRAINT CK_OPS_CONV_SOURCE_REF CHECK (
        (SOURCE_TYPE = 'CHAT' AND SOURCE_SITUATION_ID IS NULL
         AND SOURCE_RUN_ID IS NULL AND SOURCE_REPORT_ID IS NULL)
        OR
        (SOURCE_TYPE = 'SITUATION' AND SOURCE_SITUATION_ID IS NOT NULL
         AND SOURCE_RUN_ID IS NULL AND SOURCE_REPORT_ID IS NULL)
        OR
        (SOURCE_TYPE = 'RUN' AND SOURCE_SITUATION_ID IS NULL
         AND SOURCE_RUN_ID IS NOT NULL AND SOURCE_REPORT_ID IS NULL)
        OR
        (SOURCE_TYPE = 'REPORT' AND SOURCE_SITUATION_ID IS NULL
         AND SOURCE_RUN_ID IS NULL AND SOURCE_REPORT_ID IS NOT NULL)
    ),
    CONSTRAINT CK_OPS_CONV_COUNTERS CHECK (
        LAST_TURN_NO >= 0 AND LAST_MESSAGE_NO >= 0 AND ROW_VERSION > 0
    )
);

CREATE INDEX IX_OPS_CONVERSATION_SCOPE
    ON KBOT_OPS_CONVERSATION (DOMAIN_ID, STATUS, UPDATED_AT);
CREATE INDEX IX_OPS_CONV_AGENT ON KBOT_OPS_CONVERSATION (AGENT_ID);
