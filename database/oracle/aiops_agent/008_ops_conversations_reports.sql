    STARTED_AT TIMESTAMP(6) WITH TIME ZONE,
    COMPLETED_AT TIMESTAMP(6) WITH TIME ZONE,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANCEL_REQUESTED_AT TIMESTAMP(6) WITH TIME ZONE,
    CANCEL_REQUESTED_BY VARCHAR2(256 CHAR),
    CONSTRAINT UK_OPS_TURN_NO UNIQUE (CONVERSATION_ID, TURN_NO),
    CONSTRAINT UK_OPS_TURN_IDEMP UNIQUE (CONVERSATION_ID, IDEMPOTENCY_KEY),
    CONSTRAINT UK_OPS_TURN_CONVERSATION UNIQUE (TURN_ID, CONVERSATION_ID),
    CONSTRAINT FK_OPS_TURN_CONVERSATION
        FOREIGN KEY (CONVERSATION_ID, DOMAIN_ID)
        REFERENCES KBOT_OPS_CONVERSATION (CONVERSATION_ID, DOMAIN_ID)
        ON DELETE CASCADE,
    CONSTRAINT FK_OPS_TURN_TARGET
        FOREIGN KEY (RESOLVED_TARGET_ID, DOMAIN_ID)
        REFERENCES KBOT_OPS_TARGET (TARGET_ID, DOMAIN_ID),
    CONSTRAINT FK_OPS_TURN_INPUT_ART FOREIGN KEY (INPUT_ANALYSIS_ARTIFACT_ID)
        REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID),
    CONSTRAINT FK_OPS_TURN_FRAME_ART FOREIGN KEY (TASK_FRAME_ARTIFACT_ID)
        REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID),
    CONSTRAINT FK_OPS_TURN_PLAN_ART FOREIGN KEY (CURRENT_PLAN_ARTIFACT_ID)
        REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID),
    CONSTRAINT FK_OPS_TURN_ASSESS_ART FOREIGN KEY (ASSESSMENT_ARTIFACT_ID)
        REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID),
    CONSTRAINT FK_OPS_TURN_SUFF_ART FOREIGN KEY (SUFFICIENCY_ARTIFACT_ID)
        REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID),
    CONSTRAINT CK_OPS_TURN_STATUS CHECK (STATUS IN (
        'QUEUED', 'ACCEPTED', 'UNDERSTANDING', 'PLANNING', 'COLLECTING',
        'ASSESSING', 'REPLANNING', 'ANSWERING', 'WAITING_USER',
        'PROPOSAL_PENDING', 'COMPLETED', 'PARTIAL', 'FAILED', 'CANCELLED'
    )),
    CONSTRAINT CK_OPS_TURN_SUFFICIENCY CHECK (
        SUFFICIENCY_STATUS IS NULL OR SUFFICIENCY_STATUS IN (
            'ANSWERABLE', 'PARTIAL', 'NEEDS_CLARIFICATION',
            'NEEDS_EVIDENCE', 'CAPABILITY_UNAVAILABLE', 'UNSAFE'
        )
    ),
    CONSTRAINT CK_OPS_TURN_NUMBERS CHECK (
        TURN_NO > 0 AND EVENT_CURSOR >= 0 AND ROW_VERSION > 0
        AND CURRENT_PLAN_REVISION >= 0 AND INVESTIGATION_ROUND >= 0
        AND TOOL_CALL_COUNT >= 0 AND NO_PROGRESS_COUNT >= 0
    ),
    CONSTRAINT CK_OPS_TURN_CANCEL CHECK (
        (CANCEL_REQUESTED_AT IS NULL AND CANCEL_REQUESTED_BY IS NULL)
        OR
        (CANCEL_REQUESTED_AT IS NOT NULL AND CANCEL_REQUESTED_BY IS NOT NULL)
    )
);

