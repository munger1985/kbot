-- 直接检索私有历史，只保留条件及首批证据清单引用。
CREATE TABLE KBOT_KR_KNOWLEDGE_SEARCH_HISTORY (
    DOMAIN_ID NUMERIC(38, 0) NOT NULL,
    HISTORY_ID RAW(16) NOT NULL,
    SUBJECT_REF VARCHAR2(512 CHAR) NOT NULL,
    LIBRARY_ID RAW(16) NOT NULL,
    CONDITIONS_JSON JSON NOT NULL,
    MANIFEST_REF VARCHAR2(512 CHAR) NOT NULL,
    RESULT_COUNT INTEGER NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (HISTORY_ID)
);

CREATE INDEX IX_KR_SEARCH_HISTORY_OWNER ON KBOT_KR_KNOWLEDGE_SEARCH_HISTORY (DOMAIN_ID, SUBJECT_REF, CREATED_AT, HISTORY_ID);

CREATE INDEX IX_KR_SEARCH_HISTORY_EXPIRY ON KBOT_KR_KNOWLEDGE_SEARCH_HISTORY (EXPIRES_AT, HISTORY_ID);
