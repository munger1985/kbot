-- 在备份后的停写窗口执行。存在旧多文件资料时直接停止，不自动拆分、删除或重建索引。
-- 知识库 App 的文档版本已是单原文件；本脚本仅收紧 AIOps 的资料版本与文档映射。
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
    l_component VARCHAR2(64);
    l_version NUMBER;
    l_grouped NUMBER;
BEGIN
    SELECT COMPONENT, SCHEMA_VERSION INTO l_component, l_version
    FROM KBOT_V_OPS_SCHEMA_VERSION;
    IF l_component <> 'AIOPS' OR l_version <> 61 THEN
        RAISE_APPLICATION_ERROR(-20062, '单文件上传升级只适用于 AIOps Schema 61');
    END IF;
    SELECT COUNT(*) INTO l_grouped
    FROM (
        SELECT ASSET_VERSION_ID FROM KBOT_OPS_KNOWLEDGE_INDEX
        GROUP BY ASSET_VERSION_ID HAVING COUNT(*) > 1
        UNION ALL
        SELECT ASSET_VERSION_ID FROM KBOT_OPS_KNOWLEDGE_SOURCE
        WHERE SOURCE_KIND = 'MANUAL_FILE'
        GROUP BY ASSET_VERSION_ID HAVING COUNT(*) > 1
    );
    IF l_grouped > 0 THEN
        RAISE_APPLICATION_ERROR(-20063, '发现旧多文件资料，请先明确历史数据的处理方式；未执行 DDL');
    END IF;
END;
/

ALTER TABLE KBOT_OPS_KNOWLEDGE_INDEX DROP PRIMARY KEY;
DROP INDEX IX_OPS_KNOW_INDEX_VER;
ALTER TABLE KBOT_OPS_KNOWLEDGE_INDEX
    ADD CONSTRAINT PK_OPS_KNOW_INDEX PRIMARY KEY (ASSET_VERSION_ID);
CREATE INDEX IX_OPS_KNOW_INDEX_REF ON KBOT_OPS_KNOWLEDGE_INDEX (INDEX_REF_ID);

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT 'AIOPS' AS COMPONENT,
       62 AS SCHEMA_VERSION,
       'aiops-oracle-v62-single-file-upload' AS CONTRACT_VERSION
FROM DUAL;
