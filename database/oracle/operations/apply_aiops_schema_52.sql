-- AIOps Schema 51 -> 52：Run/Task 人工等待预算检查点；不修改任何目标数据库。
-- 先完成或取消旧运行，停止全部 AIOps API/Worker/Scheduler/Executor 并备份，再由所有者执行 F5。
WHENEVER OSERROR EXIT FAILURE ROLLBACK
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON
SET DEFINE OFF
SET SQLBLANKLINES ON
ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_version NUMBER;
    l_active NUMBER;
BEGIN
    SELECT schema_version INTO l_version FROM KBOT_V_OPS_SCHEMA_VERSION;
    IF l_version <> 51 THEN
        raise_application_error(-20533, '本脚本仅支持 AIOPS Schema 51');
    END IF;
    SELECT COUNT(*) INTO l_active FROM KBOT_OPS_RUN
    WHERE status NOT IN ('COMPLETED', 'PARTIAL', 'FAILED', 'CANCELLED', 'EXPIRED');
    IF l_active > 0 THEN
        raise_application_error(-20534, '升级前必须完成或取消全部旧运行，不推断旧审批的剩余预算');
    END IF;
END;
/

ALTER TABLE KBOT_OPS_RUN ADD (
    BUDGET_PAUSED_AT TIMESTAMP(6) WITH TIME ZONE,
    BUDGET_REMAINING_MS NUMBER(19),
    HUMAN_WAIT_UNTIL TIMESTAMP(6) WITH TIME ZONE,
    BUDGET_WAITED_MS NUMBER(19) DEFAULT 0 NOT NULL
);
ALTER TABLE KBOT_OPS_TASK ADD (
    EXECUTION_DEADLINE_AT TIMESTAMP(6) WITH TIME ZONE,
    BUDGET_PAUSED_AT TIMESTAMP(6) WITH TIME ZONE,
    BUDGET_REMAINING_MS NUMBER(19),
    RESUME_PENDING NUMBER(1) DEFAULT 0 NOT NULL
);

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT 'AIOPS' AS COMPONENT, 52 AS SCHEMA_VERSION,
       'aiops-oracle-v52-run-wait-budget' AS CONTRACT_VERSION FROM DUAL;

COMMIT;
