PROMPT === 正在验证业务系统直升结果 ===

DECLARE
    l_targets PLS_INTEGER;
    l_systems PLS_INTEGER;
    l_components PLS_INTEGER;
    l_system_components PLS_INTEGER;
    l_sites PLS_INTEGER;
    l_memberships PLS_INTEGER;
    l_integrity_issues PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO l_targets FROM KBOT_OPS_TARGET;
    SELECT COUNT(*) INTO l_systems FROM KBOT_OPS_BUSINESS_SYSTEM;
    SELECT COUNT(*) INTO l_components FROM KBOT_OPS_MANAGED_COMPONENT;
    SELECT COUNT(*) INTO l_system_components FROM KBOT_OPS_BUSINESS_SYSTEM_COMPONENT;
    SELECT COUNT(*) INTO l_sites FROM KBOT_OPS_BUSINESS_SYSTEM_SITE;
    SELECT COUNT(*) INTO l_memberships FROM KBOT_OPS_COMPONENT_MEMBERSHIP;

    SELECT
        (SELECT COUNT(*) FROM KBOT_OPS_TARGET t
          LEFT JOIN KBOT_OPS_COMPONENT_MEMBERSHIP m ON m.TARGET_ID = t.TARGET_ID
         WHERE m.TARGET_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_COMPONENT_MEMBERSHIP m
          LEFT JOIN KBOT_OPS_TARGET t ON t.TARGET_ID = m.TARGET_ID
         WHERE t.TARGET_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_MANAGED_COMPONENT c
          LEFT JOIN KBOT_OPS_BUSINESS_SYSTEM_COMPONENT sc ON sc.COMPONENT_ID = c.COMPONENT_ID
         WHERE sc.COMPONENT_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_PROFILE p
          LEFT JOIN KBOT_OPS_MANAGED_COMPONENT c ON c.COMPONENT_ID = p.COMPONENT_ID
         WHERE c.COMPONENT_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_DRILL d
          LEFT JOIN KBOT_OPS_MANAGED_COMPONENT c ON c.COMPONENT_ID = d.COMPONENT_ID
         WHERE c.COMPONENT_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_DRILL d
          LEFT JOIN KBOT_OPS_TARGET t ON t.TARGET_ID = d.EXECUTION_TARGET_ID
         WHERE t.TARGET_ID IS NULL)
      INTO l_integrity_issues
      FROM DUAL;

    IF l_systems <> l_targets
       OR l_components <> l_targets
       OR l_system_components <> l_targets
       OR l_sites <> l_targets
       OR l_memberships <> l_targets
       OR l_integrity_issues <> 0 THEN
        raise_application_error(-20303, '业务系统直升后完整性校验失败。');
    END IF;

    dbms_output.put_line(
        '业务系统直升验证通过：targets=' || l_targets
        || ', systems=' || l_systems
        || ', components=' || l_components
        || ', memberships=' || l_memberships
        || ', integrity_issues=' || l_integrity_issues
    );
END;
