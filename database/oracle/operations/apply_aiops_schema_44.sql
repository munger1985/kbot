CREATE TABLE KBOT_OPS_BUSINESS_SYSTEM (
    BUSINESS_SYSTEM_ID RAW(16) PRIMARY KEY,
    DOMAIN_ID NUMBER(38) NOT NULL,
    SYSTEM_CODE VARCHAR2(64 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(256 CHAR) NOT NULL,
    ENVIRONMENT VARCHAR2(16 CHAR) NOT NULL,
    IMPORTANCE_LEVEL NUMBER(1) NOT NULL,
    RESPONSIBILITY_GROUP_ID RAW(16) NOT NULL,
    DESCRIPTION CLOB,
    STATUS VARCHAR2(16 CHAR) NOT NULL,
    ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
    CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
    UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
