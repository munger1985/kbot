DECLARE
    l_component VARCHAR2(32 CHAR);
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
    l_conflicting_table_count PLS_INTEGER;
    l_target_without_group_count PLS_INTEGER;
BEGIN
    SELECT component, schema_version, contract_version
      INTO l_component, l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION;

    IF l_component <> 'AIOPS'
       OR l_schema_version <> 43
       OR l_contract_version <> 'aiops-oracle-v33' THEN
        raise_application_error(
            -20300,
            '本脚本仅支持 AIOPS/43/aiops-oracle-v33，当前为 '
            || l_component || '/' || l_schema_version || '/' || l_contract_version
        );
    END IF;

    SELECT COUNT(*)
      INTO l_conflicting_table_count
      FROM user_tables
     WHERE table_name IN (
         'KBOT_OPS_DATABASE_SYSTEM',
         'KBOT_OPS_DATABASE_SYSTEM_SITE',
         'KBOT_OPS_DATABASE_SYSTEM_MEMBER',
         'KBOT_OPS_DATABASE_SYSTEM_RELATION',
         'KBOT_OPS_BUSINESS_SYSTEM',
         'KBOT_OPS_MANAGED_COMPONENT',
         'KBOT_OPS_BUSINESS_SYSTEM_COMPONENT',
         'KBOT_OPS_BUSINESS_SYSTEM_SITE',
         'KBOT_OPS_COMPONENT_MEMBERSHIP',
         'KBOT_OPS_RESOURCE_RELATION'
     );
    IF l_conflicting_table_count <> 0 THEN
        raise_application_error(
            -20301,
            '检测到 Database System 中间表或业务系统目标表；拒绝覆盖，请先核实 Schema。'
        );
    END IF;

    SELECT COUNT(*)
      INTO l_target_without_group_count
      FROM KBOT_OPS_TARGET
     WHERE RESPONSIBILITY_GROUP_ID IS NULL;
    IF l_target_without_group_count <> 0 THEN
        raise_application_error(
            -20302,
            '有 ' || l_target_without_group_count
            || ' 个 Target 未设置责任组；请先补齐后再升级。'
        );
    END IF;
END;
