PROMPT === 验证资源图谱迁移不变量 ===

DECLARE
    l_targets PLS_INTEGER;
    l_systems PLS_INTEGER;
    l_resources PLS_INTEGER;
    l_database_resources PLS_INTEGER;
    l_system_resources PLS_INTEGER;
    l_issues PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO l_targets FROM KBOT_OPS_TARGET;
    SELECT COUNT(*) INTO l_systems FROM KBOT_OPS_BUSINESS_SYSTEM;
    SELECT COUNT(*) INTO l_resources FROM KBOT_OPS_MANAGED_RESOURCE WHERE RESOURCE_TYPE_KEY = 'DATABASE';
    SELECT COUNT(*) INTO l_database_resources FROM KBOT_OPS_DATABASE_RESOURCE;
    SELECT COUNT(*) INTO l_system_resources FROM KBOT_OPS_BUSINESS_SYSTEM_RESOURCE WHERE STATUS = 'ACTIVE';
    SELECT
        (SELECT COUNT(*) FROM KBOT_OPS_TARGET t LEFT JOIN KBOT_OPS_DATABASE_RESOURCE d ON d.TARGET_ID = t.TARGET_ID WHERE d.TARGET_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_DATABASE_RESOURCE d LEFT JOIN KBOT_OPS_MANAGED_RESOURCE r ON r.RESOURCE_ID = d.RESOURCE_ID WHERE r.RESOURCE_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_MANAGED_RESOURCE r LEFT JOIN KBOT_OPS_BUSINESS_SYSTEM_RESOURCE s ON s.RESOURCE_ID = r.RESOURCE_ID WHERE s.RESOURCE_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_PROFILE p LEFT JOIN KBOT_OPS_MANAGED_RESOURCE r ON r.RESOURCE_ID = p.RESOURCE_ID WHERE r.RESOURCE_ID IS NULL)
      + (SELECT COUNT(*) FROM KBOT_OPS_RECOVERY_DRILL d LEFT JOIN KBOT_OPS_MANAGED_RESOURCE r ON r.RESOURCE_ID = d.RESOURCE_ID WHERE r.RESOURCE_ID IS NULL)
      INTO l_issues FROM DUAL;
    IF l_systems <> l_targets OR l_resources <> l_targets
       OR l_database_resources <> l_targets OR l_system_resources <> l_targets
       OR l_issues <> 0 THEN
        raise_application_error(-20403, 'Schema 44 资源图谱迁移完整性校验失败。');
    END IF;
    dbms_output.put_line('验证通过：targets=' || l_targets
        || ', systems=' || l_systems || ', resources=' || l_resources
        || ', issues=' || l_issues);
END;
