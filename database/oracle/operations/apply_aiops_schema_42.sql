-- AIOps Schema 41 -> 42 原地升级。
-- 影响范围：恢复策略增加备份频率、成功时效和保留期，用于日常巡检确定性校验。
-- 数据策略：既有恢复策略默认启用每日备份、26 小时成功时效和 30 天保留期。
-- 前置条件：当前必须是 Schema 41 / aiops-oracle-v31。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_schema_version <> 41 OR l_contract_version <> 'aiops-oracle-v31' THEN
        RAISE_APPLICATION_ERROR(-20091, '只允许从 AIOPS Schema 41 升级到 Schema 42');
    END IF;
END;
/

ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD BACKUP_POLICY_ENABLED NUMBER(1);
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD BACKUP_FREQUENCY_HOURS NUMBER(10);
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD BACKUP_SUCCESS_MAX_AGE_HOURS NUMBER(10);
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD BACKUP_RETENTION_DAYS NUMBER(10);

UPDATE KBOT_OPS_RECOVERY_PROFILE
   SET BACKUP_POLICY_ENABLED = CASE
           WHEN JSON_EXISTS(REQUIRED_BACKUP_SOURCE_TYPES_JSON, '$[0]') THEN 1
           ELSE 0
       END,
       BACKUP_FREQUENCY_HOURS = 24,
       BACKUP_SUCCESS_MAX_AGE_HOURS = 26,
       BACKUP_RETENTION_DAYS = 30;

ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY BACKUP_POLICY_ENABLED NOT NULL;
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY BACKUP_FREQUENCY_HOURS NOT NULL;
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY BACKUP_SUCCESS_MAX_AGE_HOURS NOT NULL;
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY BACKUP_RETENTION_DAYS NOT NULL;

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    42 AS SCHEMA_VERSION,
    'aiops-oracle-v32' AS CONTRACT_VERSION
FROM DUAL;

COMMIT;

SELECT COMPONENT, SCHEMA_VERSION, CONTRACT_VERSION
  FROM KBOT_V_OPS_SCHEMA_VERSION;
