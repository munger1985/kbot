-- 知识检索 / 多媒体创作工作台表结构原地升级。
-- 影响范围：
--   1. 知识检索 Agent 版本列从 ENABLED_CAPABILITIES_JSON 改为
--      KNOWLEDGE_CORE_ID + DATA_MODEL_IDS_JSON；
--   2. 新增 X Search 运行、事件、来源表；
--   3. 新增多媒体创作工作台绑定、Run、事件、提示词版本和资产表；
--   4. 删除已退役的智能工作台 KBOT_ASST_% 业务表，不迁移历史运行或图片元数据。
-- 数据保护：不删除知识检索既有 Agent 行；旧能力 JSON 列丢弃，问数模型绑定回填为空数组。
-- 前置条件：停止 Knowledge Retrieval、Media Studio、Main API 写入进程，并完成 Schema 备份。
--           需要已存在 KBOT_PLATFORM_DOMAIN。
-- 本脚本只改表结构，不写权限目录或初始管理员。表结构完成后依次执行：
--   conda run -n kbot4 python scripts/db/apply_oracle_schema.py --foundation-only
--   database/oracle/bootstrap/knowledge_retrieval/initial_admin.sql
--   database/oracle/bootstrap/media_studio/initial_admin.sql
-- 恢复方式：Oracle DDL 会隐式提交；失败时按备份恢复。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
SET SQLBLANKLINES ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';

DECLARE
