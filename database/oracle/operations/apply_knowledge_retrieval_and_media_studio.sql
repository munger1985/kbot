    FUNCTION table_exists(p_name VARCHAR2) RETURN BOOLEAN IS
        l_count PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO l_count
          FROM USER_TABLES
         WHERE TABLE_NAME = p_name;
        RETURN l_count = 1;
    END;

    FUNCTION column_exists(p_table VARCHAR2, p_column VARCHAR2) RETURN BOOLEAN IS
        l_count PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO l_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = p_table
           AND COLUMN_NAME = p_column;
        RETURN l_count = 1;
    END;

    PROCEDURE drop_legacy_table(p_name VARCHAR2) IS
    BEGIN
        IF table_exists(p_name) THEN
            EXECUTE IMMEDIATE
                'DROP TABLE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(p_name)
                || ' CASCADE CONSTRAINTS PURGE';
            DBMS_OUTPUT.PUT_LINE('已删除 ' || p_name || '。');
        END IF;
    END;
BEGIN
    SELECT COUNT(*)
      INTO l_domain_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'KBOT_PLATFORM_DOMAIN';
    IF l_domain_count <> 1 THEN
        RAISE_APPLICATION_ERROR(-20060, '缺少 KBOT_PLATFORM_DOMAIN，不能升级产品 App 表');
    END IF;

