DECLARE
    l_missing VARCHAR2(4000);
    l_legacy VARCHAR2(4000);
    l_kr_old_column PLS_INTEGER;
    l_kr_new_column PLS_INTEGER;
    l_invalid_object_count PLS_INTEGER;
BEGIN
    SELECT LISTAGG(required.TABLE_NAME, ', ') WITHIN GROUP (ORDER BY required.TABLE_NAME)
      INTO l_missing
      FROM (
        SELECT 'KBOT_KR_AGENT' TABLE_NAME FROM DUAL UNION ALL
        SELECT 'KBOT_KR_AGENT_VERSION' FROM DUAL UNION ALL
        SELECT 'KBOT_KR_RESEARCH_RUN' FROM DUAL UNION ALL
        SELECT 'KBOT_KR_RESEARCH_EVENT' FROM DUAL UNION ALL
        SELECT 'KBOT_KR_X_SOURCE' FROM DUAL UNION ALL
        SELECT 'KBOT_MEDIA_MODEL_BINDING' FROM DUAL UNION ALL
        SELECT 'KBOT_MEDIA_RUN' FROM DUAL UNION ALL
        SELECT 'KBOT_MEDIA_RUN_EVENT' FROM DUAL UNION ALL
        SELECT 'KBOT_MEDIA_PROMPT_REVISION' FROM DUAL UNION ALL
        SELECT 'KBOT_MEDIA_ASSET' FROM DUAL
      ) required
      LEFT JOIN USER_TABLES existing ON existing.TABLE_NAME = required.TABLE_NAME
     WHERE existing.TABLE_NAME IS NULL;

    SELECT LISTAGG(legacy.TABLE_NAME, ', ') WITHIN GROUP (ORDER BY legacy.TABLE_NAME)
      INTO l_legacy
      FROM (
        SELECT 'KBOT_ASST_AGENT' TABLE_NAME FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_AGENT_VERSION' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_MODEL_BINDING' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_RUN' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_RUN_EVENT' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_X_SOURCE' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_PROMPT_REVISION' FROM DUAL UNION ALL
        SELECT 'KBOT_ASST_MEDIA_ASSET' FROM DUAL
      ) legacy
      JOIN USER_TABLES existing ON existing.TABLE_NAME = legacy.TABLE_NAME;

    SELECT COUNT(*) INTO l_kr_old_column
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'KBOT_KR_AGENT_VERSION'
       AND COLUMN_NAME = 'ENABLED_CAPABILITIES_JSON';

    SELECT COUNT(*) INTO l_kr_new_column
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'KBOT_KR_AGENT_VERSION'
       AND COLUMN_NAME IN ('KNOWLEDGE_CORE_ID', 'DATA_MODEL_IDS_JSON');

    SELECT COUNT(*)
      INTO l_invalid_object_count
      FROM USER_OBJECTS
     WHERE OBJECT_NAME IN (
         'KBOT_KR_AGENT', 'KBOT_KR_AGENT_VERSION',
         'KBOT_KR_RESEARCH_RUN', 'KBOT_KR_RESEARCH_EVENT', 'KBOT_KR_X_SOURCE',
         'KBOT_MEDIA_MODEL_BINDING', 'KBOT_MEDIA_RUN', 'KBOT_MEDIA_RUN_EVENT',
         'KBOT_MEDIA_PROMPT_REVISION', 'KBOT_MEDIA_ASSET'
     )
       AND STATUS <> 'VALID';

    IF l_missing IS NOT NULL
       OR l_legacy IS NOT NULL
       OR l_kr_old_column <> 0
       OR l_kr_new_column <> 2
       OR l_invalid_object_count <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20061,
            '知识检索 / 多媒体创作表结构校验失败：缺表='
            || NVL(l_missing, '-')
            || '，残留智能工作台表='
            || NVL(l_legacy, '-')
        );
    END IF;

    DBMS_OUTPUT.PUT_LINE('知识检索与多媒体创作工作台表结构已就绪。');
END;
