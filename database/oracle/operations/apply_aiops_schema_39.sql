-- AIOps Schema 38 -> 39 原地升级。
-- 影响范围：为 DBA 工作项补充来源 Agent，并建立责任范围查询索引。
-- 历史数据通过工作项发生记录关联的最新 Run 回填；无法归属的记录保留为空，供管理员处理。
-- 前置条件：当前必须是 Schema 38 / aiops-oracle-v28。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_schema_version <> 38 OR l_contract_version <> 'aiops-oracle-v28' THEN
        RAISE_APPLICATION_ERROR(-20091, '只允许从 AIOPS Schema 38 升级到 Schema 39');
    END IF;
END;
/

ALTER TABLE KBOT_OPS_WORK_ITEM ADD AGENT_ID RAW(16);

MERGE INTO KBOT_OPS_WORK_ITEM item
USING (
    SELECT WORK_ITEM_ID, AGENT_ID
      FROM (
          SELECT occurrence.WORK_ITEM_ID,
                 run.AGENT_ID,
                 ROW_NUMBER() OVER (
                     PARTITION BY occurrence.WORK_ITEM_ID
                     ORDER BY occurrence.OBSERVED_AT DESC,
                              occurrence.OCCURRENCE_ID DESC
                 ) AS ROW_NO
            FROM KBOT_OPS_WORK_ITEM_OCCURRENCE occurrence
            JOIN KBOT_OPS_RUN run
              ON run.OPS_RUN_ID = occurrence.OPS_RUN_ID
           WHERE run.AGENT_ID IS NOT NULL
      ) ranked
     WHERE ranked.ROW_NO = 1
) source
ON (source.WORK_ITEM_ID = item.WORK_ITEM_ID)
WHEN MATCHED THEN UPDATE SET item.AGENT_ID = source.AGENT_ID;

ALTER TABLE KBOT_OPS_WORK_ITEM ADD CONSTRAINT FK_OPS_WORK_ITEM_AGENT
    FOREIGN KEY (AGENT_ID)
    REFERENCES KBOT_OPS_AGENT (AGENT_ID);

DROP INDEX IX_OPS_WORK_ITEM_FINGERPRINT;
CREATE INDEX IX_OPS_WORK_ITEM_FINGERPRINT
    ON KBOT_OPS_WORK_ITEM (
        DOMAIN_ID, AGENT_ID, TARGET_ID, FINGERPRINT, STATUS);
CREATE INDEX IX_OPS_WORK_ITEM_AGENT
    ON KBOT_OPS_WORK_ITEM (AGENT_ID, STATUS, UPDATED_AT);
CREATE INDEX IX_OPS_WORK_ITEM_SCOPE
    ON KBOT_OPS_WORK_ITEM (
        DOMAIN_ID, AGENT_ID, TARGET_ID, RESPONSIBILITY_GROUP_ID, STATUS);

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    39 AS SCHEMA_VERSION,
    'aiops-oracle-v29' AS CONTRACT_VERSION
FROM DUAL;

COMMIT;

SELECT COMPONENT, SCHEMA_VERSION, CONTRACT_VERSION
  FROM KBOT_V_OPS_SCHEMA_VERSION;
