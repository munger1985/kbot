DECLARE
    l_component VARCHAR2(32 CHAR);
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
    l_unmapped_targets NUMBER;
BEGIN
    SELECT component, schema_version, contract_version
      INTO l_component, l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION;

    IF l_component <> 'AIOPS' OR l_schema_version <> 46
       OR l_contract_version <> 'aiops-oracle-v46-knowledge-tags' THEN
        raise_application_error(-20500, '本脚本仅支持 AIOPS Schema 46');
    END IF;

    SELECT COUNT(*)
      INTO l_unmapped_targets
      FROM KBOT_OPS_AGENT_VERSION_TARGET avt
     WHERE NOT EXISTS (
        SELECT 1
          FROM KBOT_OPS_DATABASE_RESOURCE dr
          JOIN KBOT_OPS_BUSINESS_SYSTEM_RESOURCE bsr
            ON bsr.RESOURCE_ID = dr.RESOURCE_ID
         WHERE dr.TARGET_ID = avt.TARGET_ID
           AND bsr.STATUS = 'ACTIVE'
     );
    IF l_unmapped_targets > 0 THEN
        raise_application_error(
            -20501,
            '存在未纳入业务系统资源图的 Agent Target，数量=' || l_unmapped_targets
        );
    END IF;
END;
/

PROMPT === 建立业务系统授权与资源动作策略 ===

ALTER TABLE KBOT_OPS_AGENT_VERSION ADD (
    CAPABILITIES_JSON JSON,
    KNOWLEDGE_POLICY_JSON JSON
);

UPDATE KBOT_OPS_AGENT_VERSION
   SET CAPABILITIES_JSON = JSON_ARRAY(
           'RESOURCE_CATALOG_QUERY', 'KNOWLEDGE_QA', 'MONITORING_QUERY',
           'ALERT_QUERY', 'INSPECTION_QUERY', 'REPORT_CASE_QUERY',
           'ACTIVE_DIAGNOSIS', 'CONTROLLED_CHANGE'
       ),
       KNOWLEDGE_POLICY_JSON = JSON_OBJECT(
           'enabled' VALUE true,
           'source_kinds' VALUE JSON_ARRAY('MANUAL', 'DIAGNOSIS_CASE'),
           'tag_ids' VALUE JSON_ARRAY(),
           'max_security_level' VALUE 3,
           'maximum_references' VALUE 8
       );

ALTER TABLE KBOT_OPS_AGENT_VERSION MODIFY (
    CAPABILITIES_JSON NOT NULL,
    KNOWLEDGE_POLICY_JSON NOT NULL
);

CREATE TABLE KBOT_OPS_AGENT_VERSION_SYSTEM (
    AGENT_VERSION_ID RAW(16) NOT NULL,
    BUSINESS_SYSTEM_ID RAW(16) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_OPS_AGENT_VERSION_SYSTEM
        PRIMARY KEY (AGENT_VERSION_ID, BUSINESS_SYSTEM_ID),
    CONSTRAINT FK_OPS_AGENT_VER_SYSTEM_VER FOREIGN KEY (AGENT_VERSION_ID)
        REFERENCES KBOT_OPS_AGENT_VERSION (AGENT_VERSION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_OPS_AGENT_VER_SYSTEM_SYSTEM FOREIGN KEY (BUSINESS_SYSTEM_ID)
        REFERENCES KBOT_OPS_BUSINESS_SYSTEM (BUSINESS_SYSTEM_ID)
);

CREATE INDEX IX_OPS_AGENT_VER_SYSTEM_SYSTEM
    ON KBOT_OPS_AGENT_VERSION_SYSTEM (BUSINESS_SYSTEM_ID);

CREATE TABLE KBOT_OPS_AGENT_VERSION_RESOURCE_ACTION_POLICY (
    AGENT_VERSION_ID RAW(16) NOT NULL,
    RESOURCE_ID RAW(16) NOT NULL,
    CONTROLLED_ACTION_POLICY_JSON JSON NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_OPS_AGENT_VER_RES_ACT
        PRIMARY KEY (AGENT_VERSION_ID, RESOURCE_ID),
    CONSTRAINT FK_OPS_AGENT_RES_ACT_VER FOREIGN KEY (AGENT_VERSION_ID)
        REFERENCES KBOT_OPS_AGENT_VERSION (AGENT_VERSION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_OPS_AGENT_RES_ACT_RESOURCE FOREIGN KEY (RESOURCE_ID)
        REFERENCES KBOT_OPS_MANAGED_RESOURCE (RESOURCE_ID)
);

CREATE INDEX IX_OPS_AGENT_RES_ACT_RESOURCE
    ON KBOT_OPS_AGENT_VERSION_RESOURCE_ACTION_POLICY (RESOURCE_ID);

INSERT INTO KBOT_OPS_AGENT_VERSION_SYSTEM (
    AGENT_VERSION_ID, BUSINESS_SYSTEM_ID
)
SELECT DISTINCT avt.AGENT_VERSION_ID, bsr.BUSINESS_SYSTEM_ID
  FROM KBOT_OPS_AGENT_VERSION_TARGET avt
  JOIN KBOT_OPS_DATABASE_RESOURCE dr ON dr.TARGET_ID = avt.TARGET_ID
  JOIN KBOT_OPS_BUSINESS_SYSTEM_RESOURCE bsr ON bsr.RESOURCE_ID = dr.RESOURCE_ID
 WHERE bsr.STATUS = 'ACTIVE';

INSERT INTO KBOT_OPS_AGENT_VERSION_RESOURCE_ACTION_POLICY (
    AGENT_VERSION_ID, RESOURCE_ID, CONTROLLED_ACTION_POLICY_JSON
)
SELECT avt.AGENT_VERSION_ID, dr.RESOURCE_ID, avt.CONTROLLED_ACTION_POLICY_JSON
  FROM KBOT_OPS_AGENT_VERSION_TARGET avt
  JOIN KBOT_OPS_DATABASE_RESOURCE dr ON dr.TARGET_ID = avt.TARGET_ID;

DROP TABLE KBOT_OPS_AGENT_VERSION_TARGET CASCADE CONSTRAINTS PURGE;

PROMPT === 切换 Conversation 与 Turn 范围模型 ===

ALTER TABLE KBOT_OPS_CONVERSATION ADD (CONTEXT_HINT_JSON JSON);

UPDATE KBOT_OPS_CONVERSATION c
   SET CONTEXT_HINT_JSON = (
       SELECT JSON_OBJECT(
           'source_kind' VALUE CASE c.SOURCE_TYPE
               WHEN 'SITUATION' THEN 'SITUATION'
               WHEN 'RUN' THEN 'RUN'
               WHEN 'REPORT' THEN 'REPORT'
               WHEN 'INSPECTION' THEN 'INSPECTION'
               ELSE 'BUSINESS_SYSTEM_PAGE'
           END,
           'business_system_id' VALUE LOWER(RAWTOHEX(bsr.BUSINESS_SYSTEM_ID)),
           'resource_ids' VALUE JSON_ARRAY(LOWER(RAWTOHEX(dr.RESOURCE_ID)))
       )
         FROM KBOT_OPS_DATABASE_RESOURCE dr
         JOIN KBOT_OPS_BUSINESS_SYSTEM_RESOURCE bsr
           ON bsr.RESOURCE_ID = dr.RESOURCE_ID
        WHERE dr.TARGET_ID = c.TARGET_ID
          AND bsr.STATUS = 'ACTIVE'
        FETCH FIRST 1 ROW ONLY
   );

ALTER TABLE KBOT_OPS_CONVERSATION DROP CONSTRAINT FK_OPS_CONV_TARGET;
DROP INDEX IX_OPS_CONV_TARGET;
DROP INDEX IX_OPS_CONV_SOURCE_INSP;
ALTER TABLE KBOT_OPS_CONVERSATION DROP COLUMN TARGET_ID;
CREATE INDEX IX_OPS_CONV_SOURCE_INSP
    ON KBOT_OPS_CONVERSATION (SOURCE_INSPECTION_FIRE_ID);

ALTER TABLE KBOT_OPS_CONVERSATION_TURN ADD (
