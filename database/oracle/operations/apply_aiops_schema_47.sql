DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
    l_table_count NUMBER;
    l_column_count NUMBER;
BEGIN
    SELECT schema_version, contract_version
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION;

    SELECT COUNT(*) INTO l_table_count
      FROM user_tables
     WHERE table_name IN (
        'KBOT_OPS_AGENT_VERSION_SYSTEM',
        'KBOT_OPS_AGENT_VERSION_RESOURCE_ACTION_POLICY'
     );

    SELECT COUNT(*) INTO l_column_count
      FROM user_tab_columns
     WHERE (table_name = 'KBOT_OPS_CONVERSATION' AND column_name = 'CONTEXT_HINT_JSON')
        OR (table_name = 'KBOT_OPS_CONVERSATION_TURN' AND column_name IN (
            'FOCUSED_TARGET_ID', 'CAPABILITY_PLAN_JSON',
            'SCOPE_RESOLUTION_JSON', 'CLARIFICATION_JSON',
            'ORCHESTRATION_INTERNAL_JSON'
        ));

    IF l_schema_version <> 47
       OR l_contract_version <> 'aiops-oracle-v47-unified-assistant'
       OR l_table_count <> 2
       OR l_column_count <> 6 THEN
        raise_application_error(-20502, 'Schema 47 验证失败');
    END IF;
END;
