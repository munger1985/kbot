    CAPABILITY_PLAN_JSON JSON,
    SCOPE_RESOLUTION_JSON JSON,
    CLARIFICATION_JSON JSON,
    ORCHESTRATION_INTERNAL_JSON JSON
);

UPDATE KBOT_OPS_CONVERSATION_TURN
   SET FOCUSED_TARGET_ID = RESOLVED_TARGET_ID;

ALTER TABLE KBOT_OPS_CONVERSATION_TURN
    ADD CONSTRAINT FK_OPS_TURN_FOCUSED_TARGET
    FOREIGN KEY (FOCUSED_TARGET_ID, DOMAIN_ID)
    REFERENCES KBOT_OPS_TARGET (TARGET_ID, DOMAIN_ID);

DROP INDEX IX_OPS_TURN_TARGET;
DROP INDEX IX_OPS_TURN_TARGET_OWNER;
ALTER TABLE KBOT_OPS_CONVERSATION_TURN DROP CONSTRAINT FK_OPS_TURN_TARGET;
ALTER TABLE KBOT_OPS_CONVERSATION_TURN DROP COLUMN RESOLVED_TARGET_ID;

CREATE INDEX IX_OPS_TURN_TARGET
    ON KBOT_OPS_CONVERSATION_TURN (FOCUSED_TARGET_ID, STATUS, CREATED_AT);
CREATE INDEX IX_OPS_TURN_TARGET_OWNER
    ON KBOT_OPS_CONVERSATION_TURN (FOCUSED_TARGET_ID, DOMAIN_ID);

ALTER TABLE KBOT_OPS_RUN MODIFY (TARGET_ID NULL);

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    47 AS SCHEMA_VERSION,
    'aiops-oracle-v47-unified-assistant' AS CONTRACT_VERSION
FROM DUAL;

