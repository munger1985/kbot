-- AIOps Schema 31 -> 32 原地升级。
-- 影响范围：新增运维知识资产、版本、范围、来源、KC索引引用和审核记录表。
-- 数据保护：不删除或改写既有业务行；新表只包含主键、外键和列级NOT NULL。
-- 前置条件：当前必须是Schema 31 / aiops-oracle-v21，或已部分升级到Schema 32。
-- 并发要求：执行前停止AIOps API、Worker、Scheduler和DB Executor，并完成Schema备份。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
SET SQLBLANKLINES ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF NOT (
        (l_schema_version = 31 AND l_contract_version = 'aiops-oracle-v21')
        OR
        (l_schema_version = 32 AND l_contract_version = 'aiops-oracle-v22')
    ) THEN
        RAISE_APPLICATION_ERROR(
            -20081,
            '只允许从AIOPS Schema 31 / aiops-oracle-v21升级，'
            || '或续跑Schema 32 / aiops-oracle-v22'
        );
    END IF;
END;
/

DECLARE
    PROCEDURE create_table_if_missing(
        p_table_name VARCHAR2,
        p_ddl CLOB
    ) IS
        l_count PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO l_count FROM USER_TABLES
         WHERE TABLE_NAME = p_table_name;
        IF l_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('已创建表 ' || p_table_name);
        END IF;
    END;
    PROCEDURE create_index_if_missing(
        p_index_name VARCHAR2,
        p_ddl CLOB
    ) IS
        l_count PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO l_count FROM USER_INDEXES
         WHERE INDEX_NAME = p_index_name;
        IF l_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('已创建索引 ' || p_index_name);
        END IF;
    END;
    PROCEDURE add_constraint_if_missing(
        p_constraint_name VARCHAR2,
        p_ddl CLOB
    ) IS
        l_count PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO l_count FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = p_constraint_name;
        IF l_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
            DBMS_OUTPUT.PUT_LINE('已创建外键 ' || p_constraint_name);
        END IF;
    END;
BEGIN
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_ASSET', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_ASSET (
            ASSET_ID RAW(16) PRIMARY KEY,
            DOMAIN_ID NUMBER(38) NOT NULL,
            ASSET_KIND VARCHAR2(32 CHAR) NOT NULL,
            DISPLAY_NAME VARCHAR2(256 CHAR) NOT NULL,
            STATUS VARCHAR2(32 CHAR) NOT NULL,
            CURRENT_VERSION_ID RAW(16),
            SECURITY_LEVEL NUMBER(10) NOT NULL,
            CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
            UPDATED_BY VARCHAR2(256 CHAR) NOT NULL,
            CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
            CONSTRAINT FK_OPS_KNOW_ASSET_DOMAIN FOREIGN KEY (DOMAIN_ID)
                REFERENCES KBOT_PLATFORM_DOMAIN (DOMAIN_ID)
        )~');
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_VERSION', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_VERSION (
            ASSET_VERSION_ID RAW(16) PRIMARY KEY,
            ASSET_ID RAW(16) NOT NULL,
            VERSION_NO NUMBER(19) NOT NULL,
            STATUS VARCHAR2(32 CHAR) NOT NULL,
            SOURCE_HASH VARCHAR2(64 CHAR) NOT NULL,
            PROFILE_SCHEMA_VERSION VARCHAR2(64 CHAR),
            PROFILE_JSON JSON,
            EXTRACTION_WARNINGS_JSON JSON NOT NULL,
            PUBLISHED_AT TIMESTAMP(6) WITH TIME ZONE,
            RETIRED_AT TIMESTAMP(6) WITH TIME ZONE,
            CREATED_BY VARCHAR2(256 CHAR) NOT NULL,
            CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
            CONSTRAINT FK_OPS_KNOW_VER_ASSET FOREIGN KEY (ASSET_ID)
                REFERENCES KBOT_OPS_KNOWLEDGE_ASSET (ASSET_ID)
        )~');
    add_constraint_if_missing(
        'FK_OPS_KNOW_ASSET_CUR_VER',
        'ALTER TABLE KBOT_OPS_KNOWLEDGE_ASSET ADD CONSTRAINT '
        || 'FK_OPS_KNOW_ASSET_CUR_VER FOREIGN KEY (CURRENT_VERSION_ID) '
        || 'REFERENCES KBOT_OPS_KNOWLEDGE_VERSION (ASSET_VERSION_ID)'
    );
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_SCOPE', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_SCOPE (
            SCOPE_ID RAW(16) PRIMARY KEY,
            ASSET_VERSION_ID RAW(16) NOT NULL,
            SCOPE_KIND VARCHAR2(64 CHAR) NOT NULL,
            SCOPE_VALUE VARCHAR2(512 CHAR) NOT NULL,
            NORMALIZED_VALUE VARCHAR2(512 CHAR) NOT NULL,
            SOURCE_KIND VARCHAR2(32 CHAR) NOT NULL,
            SOURCE_LOCATOR_JSON JSON,
            CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT FK_OPS_KNOW_SCOPE_VER FOREIGN KEY (ASSET_VERSION_ID)
                REFERENCES KBOT_OPS_KNOWLEDGE_VERSION (ASSET_VERSION_ID)
        )~');
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_SOURCE', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_SOURCE (
            SOURCE_ID RAW(16) PRIMARY KEY,
            ASSET_VERSION_ID RAW(16) NOT NULL,
            SOURCE_KIND VARCHAR2(32 CHAR) NOT NULL,
            SOURCE_REPORT_ID RAW(16),
            SOURCE_RUN_ID RAW(16),
            SOURCE_ARTIFACT_ID RAW(16),
            SOURCE_EXTERNAL_ID VARCHAR2(512 CHAR),
            CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
            SOURCE_LOCATOR_JSON JSON,
            CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT FK_OPS_KNOW_SOURCE_VER FOREIGN KEY (ASSET_VERSION_ID)
                REFERENCES KBOT_OPS_KNOWLEDGE_VERSION (ASSET_VERSION_ID),
            CONSTRAINT FK_OPS_KNOW_SOURCE_REPORT FOREIGN KEY (SOURCE_REPORT_ID)
                REFERENCES KBOT_OPS_REPORT (REPORT_ID),
            CONSTRAINT FK_OPS_KNOW_SOURCE_RUN FOREIGN KEY (SOURCE_RUN_ID)
                REFERENCES KBOT_OPS_RUN (OPS_RUN_ID),
            CONSTRAINT FK_OPS_KNOW_SOURCE_ART FOREIGN KEY (SOURCE_ARTIFACT_ID)
                REFERENCES KBOT_OPS_ARTIFACT (ARTIFACT_ID)
        )~');
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_INDEX', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_INDEX (
            INDEX_REF_ID RAW(16) PRIMARY KEY,
            ASSET_VERSION_ID RAW(16) NOT NULL,
            COLLECTION_ID RAW(16) NOT NULL,
            BUNDLE_ID RAW(16) NOT NULL,
            BUNDLE_REVISION_ID RAW(16) NOT NULL,
            INDEX_STATUS VARCHAR2(32 CHAR) NOT NULL,
