CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    32 AS SCHEMA_VERSION,
    'aiops-oracle-v22' AS CONTRACT_VERSION
FROM DUAL;

DECLARE
    l_table_count PLS_INTEGER;
    l_business_constraint_count PLS_INTEGER;
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT COUNT(*) INTO l_table_count FROM USER_TABLES
     WHERE TABLE_NAME IN (
        'KBOT_OPS_KNOWLEDGE_ASSET', 'KBOT_OPS_KNOWLEDGE_VERSION',
        'KBOT_OPS_KNOWLEDGE_SCOPE', 'KBOT_OPS_KNOWLEDGE_SOURCE',
        'KBOT_OPS_KNOWLEDGE_INDEX', 'KBOT_OPS_KNOWLEDGE_REVIEW'
     );
    SELECT COUNT(*) INTO l_business_constraint_count FROM USER_CONSTRAINTS
     WHERE TABLE_NAME LIKE 'KBOT\_OPS\_KNOWLEDGE\_%' ESCAPE '\'
       AND (
            (CONSTRAINT_TYPE = 'C' AND GENERATED = 'USER NAME')
         OR CONSTRAINT_TYPE = 'U'
       );
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_table_count <> 6
       OR l_business_constraint_count <> 0
       OR l_schema_version <> 32
       OR l_contract_version <> 'aiops-oracle-v22' THEN
        RAISE_APPLICATION_ERROR(-20082, 'AIOps Schema 32升级后验证失败');
    END IF;
    DBMS_OUTPUT.PUT_LINE('AIOps Schema已升级到32 / aiops-oracle-v22。');
END;
/

