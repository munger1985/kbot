            ERROR_CODE VARCHAR2(128 CHAR),
            ERROR_SUMMARY VARCHAR2(2000 CHAR),
            CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT FK_OPS_KNOW_INDEX_VER FOREIGN KEY (ASSET_VERSION_ID)
                REFERENCES KBOT_OPS_KNOWLEDGE_VERSION (ASSET_VERSION_ID)
        )~');
    create_table_if_missing('KBOT_OPS_KNOWLEDGE_REVIEW', q'~
        CREATE TABLE KBOT_OPS_KNOWLEDGE_REVIEW (
            REVIEW_ID RAW(16) PRIMARY KEY,
            ASSET_VERSION_ID RAW(16) NOT NULL,
            DECISION VARCHAR2(32 CHAR) NOT NULL,
            REVIEWER_ID VARCHAR2(256 CHAR) NOT NULL,
            COMMENT_TEXT VARCHAR2(2000 CHAR),
            BEFORE_STATUS VARCHAR2(32 CHAR) NOT NULL,
