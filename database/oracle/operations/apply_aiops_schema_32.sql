    create_index_if_missing('IX_OPS_KNOW_SOURCE_REPORT',
        'CREATE INDEX IX_OPS_KNOW_SOURCE_REPORT ON KBOT_OPS_KNOWLEDGE_SOURCE '
        || '(SOURCE_REPORT_ID)');
    create_index_if_missing('IX_OPS_KNOW_SOURCE_RUN',
        'CREATE INDEX IX_OPS_KNOW_SOURCE_RUN ON KBOT_OPS_KNOWLEDGE_SOURCE '
        || '(SOURCE_RUN_ID)');
    create_index_if_missing('IX_OPS_KNOW_SOURCE_ART',
        'CREATE INDEX IX_OPS_KNOW_SOURCE_ART ON KBOT_OPS_KNOWLEDGE_SOURCE '
        || '(SOURCE_ARTIFACT_ID)');
    create_index_if_missing('IX_OPS_KNOW_INDEX_VER',
        'CREATE INDEX IX_OPS_KNOW_INDEX_VER ON KBOT_OPS_KNOWLEDGE_INDEX '
