-- AIOps Schema 42 -> 43 原地升级。
-- 影响范围：会话报告模板增加 Domain 默认标记，正式报告增加来源会话追溯。
-- 数据策略：既有模板均非 Domain 默认；既有报告不推断来源会话。
-- 前置条件：当前必须是 Schema 42 / aiops-oracle-v32。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_schema_version <> 42 OR l_contract_version <> 'aiops-oracle-v32' THEN
        RAISE_APPLICATION_ERROR(
            -20092,
            '只允许从 AIOPS Schema 42 / aiops-oracle-v32 升级到 Schema 43'
        );
    END IF;
END;
/

ALTER TABLE KBOT_OPS_REPORT_TEMPLATE
    ADD IS_DEFAULT NUMBER(1) DEFAULT 0 NOT NULL;

ALTER TABLE KBOT_OPS_REPORT
    ADD SOURCE_CONVERSATION_ID RAW(16);

ALTER TABLE KBOT_OPS_REPORT
    ADD CONSTRAINT FK_OPS_REPORT_CONVERSATION
    FOREIGN KEY (SOURCE_CONVERSATION_ID)
    REFERENCES KBOT_OPS_CONVERSATION (CONVERSATION_ID);

CREATE INDEX IX_OPS_REPORT_CONVERSATION
    ON KBOT_OPS_REPORT
       (SOURCE_CONVERSATION_ID, TEMPLATE_ID, IS_CURRENT, REPORT_VERSION);

CREATE OR REPLACE VIEW KBOT_V_OPS_REPORT AS
SELECT
    t.DOMAIN_ID,
    LOWER(
        SUBSTR(RAWTOHEX(r.REPORT_ID), 1, 8) || '-' ||
        SUBSTR(RAWTOHEX(r.REPORT_ID), 9, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.REPORT_ID), 13, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.REPORT_ID), 17, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.REPORT_ID), 21, 12)
    ) AS REPORT_ID,
    LOWER(
        SUBSTR(RAWTOHEX(r.OPS_RUN_ID), 1, 8) || '-' ||
        SUBSTR(RAWTOHEX(r.OPS_RUN_ID), 9, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.OPS_RUN_ID), 13, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.OPS_RUN_ID), 17, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.OPS_RUN_ID), 21, 12)
    ) AS OPS_RUN_ID,
    CASE
        WHEN r.SOURCE_CONVERSATION_ID IS NULL THEN NULL
        ELSE LOWER(
            SUBSTR(RAWTOHEX(r.SOURCE_CONVERSATION_ID), 1, 8) || '-' ||
            SUBSTR(RAWTOHEX(r.SOURCE_CONVERSATION_ID), 9, 4) || '-' ||
            SUBSTR(RAWTOHEX(r.SOURCE_CONVERSATION_ID), 13, 4) || '-' ||
            SUBSTR(RAWTOHEX(r.SOURCE_CONVERSATION_ID), 17, 4) || '-' ||
            SUBSTR(RAWTOHEX(r.SOURCE_CONVERSATION_ID), 21, 12)
        )
    END AS SOURCE_CONVERSATION_ID,
    LOWER(
        SUBSTR(RAWTOHEX(r.TARGET_ID), 1, 8) || '-' ||
        SUBSTR(RAWTOHEX(r.TARGET_ID), 9, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.TARGET_ID), 13, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.TARGET_ID), 17, 4) || '-' ||
        SUBSTR(RAWTOHEX(r.TARGET_ID), 21, 12)
    ) AS TARGET_ID,
    t.DISPLAY_NAME AS TARGET_NAME,
    r.REPORT_KEY,
    r.REPORT_VERSION,
    r.TEMPLATE_ID AS TEMPLATE_REF,
    r.TEMPLATE_VERSION,
    r.REPORT_TYPE,
    r.TITLE,
    r.STATUS,
    r.PERIOD_START,
    r.PERIOD_END,
    r.BASELINE_START,
    r.BASELINE_END,
    r.AFTER_START,
    r.AFTER_END,
    r.RESULT,
    r.SUMMARY,
    r.SECURITY_LEVEL,
    r.CREATED_AT,
    r.UPDATED_AT
FROM KBOT_OPS_REPORT r
JOIN KBOT_OPS_TARGET t ON t.TARGET_ID = r.TARGET_ID
WHERE r.IS_CURRENT = 1;

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    43 AS SCHEMA_VERSION,
    'aiops-oracle-v33' AS CONTRACT_VERSION
FROM DUAL;

COMMIT;

SELECT COMPONENT, SCHEMA_VERSION, CONTRACT_VERSION
  FROM KBOT_V_OPS_SCHEMA_VERSION;
