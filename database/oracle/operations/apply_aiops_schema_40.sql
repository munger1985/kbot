-- AIOps Schema 39 -> 40 原地升级。
-- 影响范围：恢复策略增加是否要求定期恢复演练的显式开关。
-- 现有策略保持要求演练，避免升级后静默停止既有计划。
-- 前置条件：当前必须是 Schema 39 / aiops-oracle-v29。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_schema_version <> 39 OR l_contract_version <> 'aiops-oracle-v29' THEN
        RAISE_APPLICATION_ERROR(-20091, '只允许从 AIOPS Schema 39 升级到 Schema 40');
    END IF;
END;
/

ALTER TABLE KBOT_OPS_RECOVERY_PROFILE ADD DRILL_REQUIRED NUMBER(1);
UPDATE KBOT_OPS_RECOVERY_PROFILE SET DRILL_REQUIRED = 1;
ALTER TABLE KBOT_OPS_RECOVERY_PROFILE MODIFY DRILL_REQUIRED NOT NULL;

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    40 AS SCHEMA_VERSION,
    'aiops-oracle-v30' AS CONTRACT_VERSION
FROM DUAL;

COMMIT;

SELECT COMPONENT, SCHEMA_VERSION, CONTRACT_VERSION
  FROM KBOT_V_OPS_SCHEMA_VERSION;
