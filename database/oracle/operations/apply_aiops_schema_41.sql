-- AIOps Schema 40 -> 41 原地升级。
-- 影响范围：责任归属收口到 Target；Agent 只保留 Target 能力关联。
-- 数据策略：保留 Target 显式归属，仅对空值继承当前 Agent 的责任组。
-- 如同一 Target 从多个 Agent 得到不同责任组，在任何 DDL 前中止。
-- 前置条件：当前必须是 Schema 40 / aiops-oracle-v30。

SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

ALTER SESSION SET TIME_ZONE = '+00:00';
ALTER SESSION SET DDL_LOCK_TIMEOUT = 60;

DECLARE
    l_schema_version NUMBER;
    l_contract_version VARCHAR2(64 CHAR);
    l_conflict_count NUMBER;
BEGIN
    SELECT SCHEMA_VERSION, CONTRACT_VERSION
      INTO l_schema_version, l_contract_version
      FROM KBOT_V_OPS_SCHEMA_VERSION
     WHERE COMPONENT = 'AIOPS';
    IF l_schema_version <> 40 OR l_contract_version <> 'aiops-oracle-v30' THEN
        RAISE_APPLICATION_ERROR(-20091, '只允许从 AIOPS Schema 40 升级到 Schema 41');
    END IF;

    SELECT COUNT(*)
      INTO l_conflict_count
      FROM (
            SELECT binding.TARGET_ID
              FROM KBOT_OPS_AGENT_VERSION_TARGET binding
              JOIN KBOT_OPS_AGENT agent
                ON agent.CURRENT_VERSION_ID = binding.AGENT_VERSION_ID
              JOIN KBOT_OPS_TARGET target
                ON target.TARGET_ID = binding.TARGET_ID
             WHERE target.DEFAULT_RESPONSIBILITY_GROUP_ID IS NULL
               AND agent.DEFAULT_RESPONSIBILITY_GROUP_ID IS NOT NULL
             GROUP BY binding.TARGET_ID
            HAVING COUNT(DISTINCT agent.DEFAULT_RESPONSIBILITY_GROUP_ID) > 1
      );
    IF l_conflict_count <> 0 THEN
        RAISE_APPLICATION_ERROR(
            -20092,
            '存在 ' || l_conflict_count
            || ' 个 Target 被不同责任组的 Agent 共同关联，请先人工确定归属'
        );
    END IF;
END;
/

ALTER TABLE KBOT_OPS_TARGET ADD RESPONSIBILITY_GROUP_ID RAW(16);

UPDATE KBOT_OPS_TARGET
   SET RESPONSIBILITY_GROUP_ID = DEFAULT_RESPONSIBILITY_GROUP_ID
 WHERE DEFAULT_RESPONSIBILITY_GROUP_ID IS NOT NULL;

UPDATE KBOT_OPS_TARGET target
   SET target.RESPONSIBILITY_GROUP_ID = (
       SELECT HEXTORAW(MIN(RAWTOHEX(agent.DEFAULT_RESPONSIBILITY_GROUP_ID)))
         FROM KBOT_OPS_AGENT_VERSION_TARGET binding
         JOIN KBOT_OPS_AGENT agent
           ON agent.CURRENT_VERSION_ID = binding.AGENT_VERSION_ID
        WHERE binding.TARGET_ID = target.TARGET_ID
          AND agent.DEFAULT_RESPONSIBILITY_GROUP_ID IS NOT NULL
   )
 WHERE target.RESPONSIBILITY_GROUP_ID IS NULL
   AND EXISTS (
       SELECT 1
         FROM KBOT_OPS_AGENT_VERSION_TARGET binding
         JOIN KBOT_OPS_AGENT agent
           ON agent.CURRENT_VERSION_ID = binding.AGENT_VERSION_ID
        WHERE binding.TARGET_ID = target.TARGET_ID
          AND agent.DEFAULT_RESPONSIBILITY_GROUP_ID IS NOT NULL
   );

ALTER TABLE KBOT_OPS_TARGET DROP CONSTRAINT FK_OPS_TARGET_RESP_GROUP;
DROP INDEX IX_OPS_TARGET_RESP_GROUP;
ALTER TABLE KBOT_OPS_AGENT DROP CONSTRAINT FK_OPS_AGENT_RESP_GROUP;
DROP INDEX IX_OPS_AGENT_RESP_GROUP;

ALTER TABLE KBOT_OPS_TARGET DROP COLUMN DEFAULT_RESPONSIBILITY_GROUP_ID;
ALTER TABLE KBOT_OPS_AGENT DROP COLUMN DEFAULT_RESPONSIBILITY_GROUP_ID;

ALTER TABLE KBOT_OPS_TARGET ADD CONSTRAINT FK_OPS_TARGET_RESP_GROUP
    FOREIGN KEY (RESPONSIBILITY_GROUP_ID)
    REFERENCES KBOT_OPS_RESPONSIBILITY_GROUP (RESPONSIBILITY_GROUP_ID);
CREATE INDEX IX_OPS_TARGET_RESP_GROUP
    ON KBOT_OPS_TARGET (RESPONSIBILITY_GROUP_ID);

UPDATE KBOT_OPS_WORK_ITEM
   SET ASSIGNMENT_SOURCE = 'TARGET_RESPONSIBILITY'
 WHERE ASSIGNMENT_SOURCE IN ('TARGET_DEFAULT', 'AGENT_DEFAULT');

CREATE OR REPLACE VIEW KBOT_V_OPS_SCHEMA_VERSION AS
SELECT
    'AIOPS' AS COMPONENT,
    41 AS SCHEMA_VERSION,
    'aiops-oracle-v31' AS CONTRACT_VERSION
FROM DUAL;

COMMIT;

SELECT COMPONENT, SCHEMA_VERSION, CONTRACT_VERSION
  FROM KBOT_V_OPS_SCHEMA_VERSION;

SELECT COUNT(*) AS TARGET_WITH_RESPONSIBILITY_GROUP
  FROM KBOT_OPS_TARGET
 WHERE RESPONSIBILITY_GROUP_ID IS NOT NULL;
