import assert from 'node:assert/strict';
import {createRunFixture} from './aiops_runs_fixture.mjs';
const run={ops_run_id:'run1',status:'CANCELLED',workflow_kind:'CHAT_TURN',readonly_lifecycle:{items:[{lease_id:'<script>unsafe</script>',status:'TERMINATION_UNKNOWN'},{lease_id:'lease2',status:'CANCEL_REQUESTED',observation:{db_type:'ORACLE'}},{lease_id:'lease3',status:'TERMINATION_CONFIRMED',observation:{db_type:'MYSQL'}}],truncated:true}};
const f=createRunFixture(run,{}),html=()=>f.node('run-lifecycle').innerHTML;
await f.open(run.ops_run_id);
for(const text of ['只读查询清理回执','终止状态未知，不能确认数据库已停止','已请求取消，尚未确认终止','自有查询清理已获协议确认','最近 50 条']) assert.ok(html().includes(text));
assert.ok(html().includes(f.escape('<script>unsafe</script>'))&&!html().includes('<script>unsafe</script>'));
assert.equal(f.timers.size,1,'终态仍允许回执迟到后的有界刷新');
for(let i=0;i<3;i++) await f.tick();
assert.equal(f.timers.size,0,'未确认不能无限后台轮询');
await f.open(run.ops_run_id);assert.equal(f.timers.size,1,'手动刷新可重新等待迟到回执');
run.readonly_lifecycle.items=[{lease_id:'lease3',status:'TERMINATION_CONFIRMED'}];await f.tick();
assert.equal(f.timers.size,0,'确认后停止终态轮询');
await f.open(run.ops_run_id);f.close();assert.equal(f.timers.size,0);assert.equal(f.node('run-drawer').open,false);
assert.ok(f.calls.every(row=>row.path.includes('/runs/run1')));
console.log('PASS 只读清理回执、未知边界、转义、终态有界刷新及手动恢复');
