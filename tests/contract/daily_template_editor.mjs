// 纯展示模型回归，不连接 API；两端模型与样式必须同步。
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const ammolite=path.basename(root)==="ammolite_cube" ? root : path.resolve(root,"../ammolite_cube");
const kbot=path.basename(root)==="kbot4" ? root : path.resolve(root,"../kbot4");
const portalDir=path.join(ammolite,"apps/portal-web/src/features/aiops/management");
const staticDir=path.join(kbot,"ui/aiops");
const source=await fs.readFile(path.join(portalDir,"daily-template-model.js"),"utf8");
assert.equal(source,await fs.readFile(path.join(staticDir,"js/daily-template-model.js"),"utf8"));
assert.equal(await fs.readFile(path.join(portalDir,"daily-template-editor.css"),"utf8"),await fs.readFile(path.join(staticDir,"css/daily-template-editor.css"),"utf8"));
const model=await import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const catalog=JSON.parse(await fs.readFile(process.argv[2] || "/tmp/daily-template-stepper-20261103/catalog.json","utf8"));
assert.equal(model.themes(catalog).length,9);
const selectedTopics=model.selectedTopics(catalog,model.checks(catalog).map(check=>check.check_id));
assert.ok(selectedTopics.length);
assert.ok(selectedTopics.every(topic=>new Set(topic.checks).size===topic.checks.length));
assert.deepEqual(model.selectedTopics(catalog,["unknown"]),[{title:"未识别检查",checks:["unknown"]}]);
const original=JSON.stringify(catalog),draft=model.createDraft(catalog),automatic=model.automaticIds(catalog);
assert.ok(automatic.size);
assert.ok(draft.selected.length);
assert.ok(draft.selected.every(id=>automatic.has(id)));
assert.ok(model.checkGroups(catalog,"SESSIONS",true).length);
for(const theme of model.themes(catalog))for(const group of model.checkGroups(catalog,theme.section_id,false))for(const item of group.checks)assert.equal(automatic.has(item.check_id),false);
const mixed={checks:[{check_id:"current",availability:"READY"},{check_id:"future",availability:"READY"},{check_id:"planned",availability:"PLANNED"}]};
assert.deepEqual(model.groupState(mixed,["current"]),{checked:false,mixed:true,count:1,total:2});
assert.deepEqual(model.toggleGroup(mixed,["elsewhere","current"],true),["elsewhere","current","future"]);
assert.deepEqual(model.toggleGroup(mixed,["elsewhere","current"],false),["elsewhere"]);
assert.deepEqual(model.groupIds(mixed),["current","future"]);
const layout=draft.layout;
assert.equal(model.normalPreference(layout),"FULL");
model.setNormalPreference(layout,"SUMMARY");
assert.ok(model.editableRegions(layout).every(item=>item.normal_detail==="SUMMARY"));
assert.equal(layout.sections.find(item=>item.section_id==="SQL").normal_detail,"FULL");
layout.sections.find(item=>item.section_id==="RESOURCES").normal_detail="FULL";
assert.equal(model.normalPreference(layout),"CUSTOM");
const retained=structuredClone(layout);
model.setNormalPreference(layout,"CUSTOM");
assert.deepEqual(layout,retained);
assert.equal(model.canConfigureStatistics(catalog,"SQL"),false);
assert.equal(model.canConfigureStatistics(catalog,"RESOURCES"),true);
assert.deepEqual(model.unavailableIds(catalog,["unknown","oracle.storage.row_chaining"]),["unknown","oracle.storage.row_chaining"]);
const base=model.createDraft(catalog),changed=structuredClone(base);
changed.selected.pop();changed.layout.title="新的日报标题";
assert.deepEqual(model.changeSummary(changed,base),{added:0,removed:1,layoutChanged:true});
const persistedDraft={display_name:"保存的草稿",selected_check_ids:base.selected,daily_report_layout:base.layout};
const published={display_name:"已发布内容",selected_check_ids:[],daily_report_layout:catalog.daily_report_layout};
assert.equal(model.createDraft(catalog,{draft:persistedDraft,definition:published}).name,"保存的草稿");
assert.equal(model.createDraft(catalog,{draft:null,definition:published}).name,"已发布内容");
assert.deepEqual(model.createDraft(catalog,{draft:persistedDraft}).selected,base.selected);
assert.equal(JSON.stringify(catalog),original);
assert.throws(()=>model.createDraft({...catalog,daily_check_policy:{}}),/保障策略/);
const future=structuredClone(catalog);
future.report_sections[3].title="共享容量";
future.groups.push({checks:[{check_id:"future.capacity",display_name:"未来容量",availability:"READY",report_section:"CAPACITY",supported_db_types:["FUTURE_ENGINE"],default_for:["DAILY"]}]});
assert.ok(model.engines(future).includes("FUTURE_ENGINE"));
assert.ok(model.checkGroups(future,"CAPACITY",false).some(group=>group.title==="未来容量"));
console.log("日报分步编辑模型：策略来源、九主题、跨库选择、部分选择、不可用项、版式差异、未来适配与两端一致性通过。");
