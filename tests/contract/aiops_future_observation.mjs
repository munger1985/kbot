import assert from 'node:assert/strict';
import {createRunFixture} from './aiops_runs_fixture.mjs';
const run={ops_run_id:'future-run',workflow_kind:'EVIDENCE_FOLLOWUP',status:'RUNNING',row_version:7};
const sql='SELECT "<unsafe>" FROM orders';
const result={payload:{observation_series:{completed_count:1,requested:{count:3,interval_seconds:30}},tool_outcomes:[{observation:{captured_at:'2026-10-28T06:00:00Z',row_count:1,truncated:false,columns:[{name:'sql_text'}],rows:[[sql]]}},{observation:{captured_at:'2026-10-28T06:00:30Z',row_count:0,truncated:false,columns:[],rows:[]},gap:{code:'FOLLOWUP_PENDING',detail:'待采样'}}]}};
const f=createRunFixture(run,result);
await f.open(run.ops_run_id);
const html=()=>f.node('run-result').innerHTML;
assert.ok(html().includes('后台未来观察'));
assert.ok(html().includes('已采集 1/3 次'));
assert.ok(html().includes('不覆盖过去请求窗口'));
assert.ok(html().includes(f.escape(sql))&&!html().includes(sql));
assert.ok(html().includes('此采集时点没有匹配记录；不是未执行查询。'));
assert.ok(html().includes('等待后续采样时点'));
assert.equal(f.timers.size,1);
await f.open(run.ops_run_id);
assert.equal(f.timers.size,1,'手动刷新不能叠加轮询');
const pending=f.cancelObservation();f.settleConfirmation(true);await pending;
const command=f.calls.find(item=>item.path.endsWith('/commands')),body=JSON.parse(command.init.body);
assert.equal(body.ops_run_id,'future-run');
assert.deepEqual(body.command,{command_type:'CANCEL_RUN',expected_row_version:7});
assert.ok(body.command_id&&body.idempotency_key);
assert.equal(f.timers.size,0);
assert.equal(f.node('cancel-future-observation').hidden,true);
assert.ok(html().includes(f.escape(sql)),'取消不能抹去已采集的原始时点');
console.log('PASS 后台未来观察结果、转义、刷新及取消合同');
