"""每个端口调用都带当前 Scope 与 Snapshot，没有公共文档目录。"""

from typing import Protocol

from ..contracts.identity import AppBackendBinding, AuthorizedScope, EvidenceKey, RetrievalSnapshot
from ..contracts.query import BackendCapabilities, QueryInput
from ..contracts.retrieval import ChannelRequest, EvidenceBatch, RelationPage, RelationRequest, ValidationResult
from ..retrieval.fusion import ChannelShard
from ..retrieval.selection import CandidateTargetMatch, CoverageTarget
from .ordered import OrderedPage


class AppBoundBackend(Protocol):
    binding: AppBackendBinding
    capabilities: BackendCapabilities

    async def snapshot(self, scope: AuthorizedScope) -> RetrievalSnapshot: ...
    async def search_ordered(self, query: QueryInput, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> OrderedPage: ...
    async def search_lexical(self, request: ChannelRequest, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> tuple[ChannelShard, ...]: ...
    async def search_dense(self, request: ChannelRequest, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> tuple[ChannelShard, ...]: ...
    async def search_multivector(self, request: ChannelRequest, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> tuple[ChannelShard, ...]: ...
    async def search_near_duplicate(self, request: ChannelRequest, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> tuple[ChannelShard, ...]: ...
    async def load_evidence(self, keys: tuple[EvidenceKey, ...], scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> EvidenceBatch: ...
    async def follow_relations(self, request: RelationRequest, scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> RelationPage: ...
    async def revalidate(self, keys: tuple[EvidenceKey, ...], scope: AuthorizedScope, snapshot: RetrievalSnapshot) -> ValidationResult: ...
    async def match_targets(self, keys: tuple[EvidenceKey, ...], targets: tuple[CoverageTarget, ...], scope: AuthorizedScope,
                            snapshot: RetrievalSnapshot) -> tuple[CandidateTargetMatch, ...]: ...
